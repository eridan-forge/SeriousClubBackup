using System;

namespace серьёзный.Модели
{
    public class АккаунтИгрока
    {
        // =========================================================
        // ИДЕНТИФИКАТОР
        // =========================================================

        public Guid Id { get; set; } =
            Guid.NewGuid();


        // =========================================================
        // ДАННЫЕ АККАУНТА
        // =========================================================

        // ФИО игрока — отображаемое имя везде, КРОМЕ входа
        // (ОкноИгрока, чат, соцфункции, карточки в админке).
        public string Имя { get; set; } =
            string.Empty;

        // Логин для входа через Экран Клуба. Хранится нормализованным:
        // 11 цифр, начинается с 7 (например "79991234567").
        public string Телефон { get; set; } =
            string.Empty;

        public string Пароль { get; set; } =
            string.Empty;


        // =========================================================
        // ВРЕМЯ
        // =========================================================

        public TimeSpan ОсталосьВремени { get; set; } =
            TimeSpan.Zero;


        // =========================================================
        // СТАТИСТИКА
        // =========================================================

        public TimeSpan ВсегоСыграно { get; set; } =
            TimeSpan.Zero;

        public int ВсегоСеансов { get; set; }

        public DateTime? ПоследнийСеанс { get; set; }


        // =========================================================
        // ОТОБРАЖЕНИЕ ВРЕМЕНИ
        // =========================================================

        public string ОсталосьСтрокой
        {
            get
            {
                var время =
                    ОсталосьВремени < TimeSpan.Zero
                        ? TimeSpan.Zero
                        : ОсталосьВремени;

                if (время.TotalHours >= 100)
                {
                    return
                        $"{(int)время.TotalHours}:{время.Minutes:00}";
                }

                return время.ToString(
                    @"hh\:mm");
            }
        }


        // =========================================================
        // ИМЯ
        // =========================================================

        public string ПолноеИмя
        {
            get
            {
                return string.IsNullOrWhiteSpace(Имя)
                    ? "Игрок"
                    : Имя;
            }
        }

        public string ОтображаемоеИмя =>
            string.IsNullOrWhiteSpace(Имя)
                ? "Игрок"
                : Имя;


        // =========================================================
        // ТЕЛЕФОН
        // =========================================================

        // Человеческий вид: +7 (999) 123-45-67.
        // Если формат нестандартный — возвращает как есть,
        // чтобы ничего не терять при отображении.
        public string ТелефонОтображаемый
        {
            get
            {
                if (string.IsNullOrWhiteSpace(Телефон) ||
                    Телефон.Length != 11)
                {
                    return Телефон;
                }

                return
                    $"+{Телефон[0]} " +
                    $"({Телефон.Substring(1, 3)}) " +
                    $"{Телефон.Substring(4, 3)}-" +
                    $"{Телефон.Substring(7, 2)}-" +
                    $"{Телефон.Substring(9, 2)}";
            }
        }
    }
}