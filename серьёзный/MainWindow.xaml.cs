        private void ПолученоСообщениеЧата(
            СообщениеЧата чат)
        {
            if (приложениеЗакрывается)
            {
                return;
            }

            var активныйСеанс =
                сервисСеансов
                    .ПолучитьАктивные()
                    .FirstOrDefault(
                        x =>
                            x.КомпьютерId ==
                            чат.КомпьютерId);

            var запись =
                new ЗаписьЧата
                {
                    КомпьютерId =
                        чат.КомпьютерId,

                    Имя =
                        чат.Имя,

                    Текст =
                        чат.Текст,

                    Время =
                        DateTime.Now,

                    ОтАдминистратора =
                        !чат.ОтИгрока,

                    АккаунтGuid =
                        активныйСеанс?.АккаунтGuid,

                    Прочитано =
                        окноЧата != null &&
                        окноЧата.IsVisible
                };

            сервисЧата.Добавить(
                запись);

            if (окноЧата != null &&
                окноЧата.IsVisible)
            {
                окноЧата.ДобавитьСообщение(
                    запись);
            }
        }


        

        

        private void Чат_Click(
            object sender,
            RoutedEventArgs e)
        {
            if (приложениеЗакрывается)
            {
