        private static string
            ПолучитьИмяИзСнимка(
                object снимок)
        {
            if (снимок == null)
            {
                return "Аноним";
            }

            var свойство =
                снимок.GetType()
                    .GetProperty(
                        "ИмяКлиента");

            if (свойство != null &&
                свойство.GetValue(
                    снимок) is string имя &&
                !string.IsNullOrWhiteSpace(
                    имя))
            {
                return имя;
            }

            var свойствоИгрок =
                снимок.GetType()
                    .GetProperty(
                        "Игрок");

            if (свойствоИгрок != null &&
                свойствоИгрок.GetValue(
                    снимок) is string игрок &&
                !string.IsNullOrWhiteSpace(
                    игрок))
            {
                return игрок;
            }

            return "Аноним";
        }


        private static decimal
            ПолучитьСтоимостьИзСнимка(
                object снимок)
        {
            if (снимок == null)
            {
                return 0m;
            }

            var свойство =
                снимок.GetType()
                    .GetProperty(
                        "Стоимость");

            if (свойство == null)
            {
                return 0m;
            }

            var значение =
                свойство.GetValue(
                    снимок);

            return значение switch
            {
                decimal сумма =>
                    сумма,

                double сумма =>
                    (decimal)сумма,

                float сумма =>
                    (decimal)сумма,

                int сумма =>
                    сумма,

                long сумма =>
                    сумма,

                _ =>
                    0m
            };
        }


