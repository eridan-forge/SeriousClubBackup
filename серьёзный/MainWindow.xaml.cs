        // =========================================================
        // WAKE ON LAN
        // =========================================================

        public static async Task<bool>
            ВключитьAsync(
                string mac)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(
                        mac))
                {
                    return false;
                }

                byte[] macBytes =
                    mac
                        .Split(
                            '-',
                            ':')
                        .Where(
                            x =>
                                !string.IsNullOrWhiteSpace(
                                    x))
                        .Select(
                            x =>
                                Convert.ToByte(
                                    x,
                                    16))
                        .ToArray();

                if (macBytes.Length != 6)
                {
                    return false;
                }

                byte[] packet =
                    new byte[102];

                for (int i = 0; i < 6; i++)
                {
                    packet[i] =
                        0xFF;
                }

                for (int i = 0; i < 16; i++)
                {
                    Buffer.BlockCopy(
                        macBytes,
                        0,
                        packet,
                        6 + i * 6,
                        6);
                }

                var nic =
                    NetworkInterface
                        .GetAllNetworkInterfaces()
                        .FirstOrDefault(
                            x =>
                                x.NetworkInterfaceType ==
                                    NetworkInterfaceType.Ethernet &&
                                x.OperationalStatus ==
                                    OperationalStatus.Up);

                if (nic == null)
                {
                    return false;
                }

                var ip =
                    nic.GetIPProperties()
                        .UnicastAddresses
                        .FirstOrDefault(
                            x =>
                                x.Address.AddressFamily ==
                                AddressFamily.InterNetwork);

                if (ip == null)
                {
                    return false;
                }

                using var udp =
                    new UdpClient(
                        new IPEndPoint(
                            ip.Address,
                            0));

                udp.EnableBroadcast =
                    true;

                var broadcast =
                    new IPEndPoint(
                        IPAddress.Broadcast,
                        9);

                for (int i = 0; i < 5; i++)
                {
                    await udp.SendAsync(
                        packet,
                        packet.Length,
                        broadcast);

                    await Task.Delay(
                        60);
                }

                return true;
            }
            catch
            {
                return false;
            }
        }

