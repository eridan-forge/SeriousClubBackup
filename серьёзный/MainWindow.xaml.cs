        private void ОбновитьИнформациюПК()
        {
            if (ВыборПК.SelectedIndex < 0)
            {
                return;
            }

            if (ВыборПК.SelectedItem
                is not ЗаписьПК выбранный)
            {
                return;
            }

            var id =
                выбранный.Id;

            if (подключения.TryGetValue(
                    id,
                    out var подключение))
            {
                ИнформацияПК.Text =
                    $"ПК-{id}\n" +
                    $"Имя: {подключение.ИмяКомпьютера}\n" +
                    $"IP: {подключение.IPАдрес}\n" +
                    $"Статус: ПОДКЛЮЧЁН";
            }
            else
            {
                ИнформацияПК.Text =
                    $"ПК-{id}\n" +
                    $"Статус: НЕ ПОДКЛЮЧЁН";
            }
        }


        private ПодключениеПатруля?
            ПолучитьВыбранныйПК()
        {
            if (ВыборПК.SelectedItem
                is not ЗаписьПК выбранный)
            {
                return null;
            }

            if (!подключения.TryGetValue(
                    выбранный.Id,
                    out var подключение))
            {
                MessageBox.Show(
                    $"{выбранный.Название} сейчас не подключён.",
                    "Серьёзный",
                    MessageBoxButton.OK,
                    MessageBoxImage.Warning);

                return null;
            }

            return подключение;
        }


        // =========================================================
        // SEND COMMAND
        // =========================================================

        private async Task<bool>
    ОтправитьКомандуAsync(
        КомандаПК команда,
        string? текст = null,
        string? файл = null,
        int? компьютерId = null,
        string? имяОтправителя = null,
         string? аудиоBase64 = null,
         Guid? аккаунтId = null,
         string? имяАккаунта = null,
          int? сеансId = null,
           int? длительностьСекунд = null,
           string? параметры = null)
        {
            if (приложениеЗакрывается)
            {
                return false;
            }

            ПодключениеПатруля? подключение;

            if (компьютерId.HasValue)
            {
                подключения.TryGetValue(
                    компьютерId.Value,
                    out подключение);
            }
            else
            {
                подключение =
                    ПолучитьВыбранныйПК();
            }

            if (подключение == null)
            {
                return false;
            }

            var данные =
                new серьёзный.Сеть.КомандаПатрулю
                {
                    Команда =
                        команда,

                    Текст =
                        текст,

                    Файл =
                        файл,

                    ИмяОтправителя =
                        имяОтправителя,

                    АудиоBase64 =
                    аудиоBase64,

                    АккаунтId =
                    аккаунтId,

                    ИмяАккаунта =
                    имяАккаунта,

                    СеансId =
                     сеансId,

                    ДлительностьСекунд =
                     длительностьСекунд,

                    Параметры =
                     параметры
                };

            var сообщение =
                СетевоеСообщение.Создать(
                    ТипСообщения.Команда);

            сообщение.КомпьютерId =
                подключение.КомпьютерId;

            сообщение.УстановитьДанные(
                данные);

            var успешно =
                await подключение
                    .ОтправитьAsync(
                        сообщение);

            if (!успешно &&
                !приложениеЗакрывается)
            {
                Dispatcher.Invoke(
                    () =>
                    {
                        ТекстСостояния.Text =
                            "Не удалось отправить команду.";
                    });
            }

            return успешно;
        }


