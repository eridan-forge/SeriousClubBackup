        private static TimeSpan
            ПолучитьВремяПаузыИзСнимка(
                object снимок)
        {
            if (снимок == null)
            {
                return TimeSpan.Zero;
            }

            var свойство =
                снимок.GetType()
                    .GetProperty(
                        "ВремяПаузы");

            if (свойство == null)
            {
                return TimeSpan.Zero;
            }

            var значение =
                свойство.GetValue(
                    снимок);

            return значение is TimeSpan время
                ? время
                : TimeSpan.Zero;
        }


        private static TimeSpan
            ПолучитьОстатокНаАккаунтИзСнимка(
                object снимок)
        {
            if (снимок == null)
            {
                return TimeSpan.Zero;
            }

            var свойство =
                снимок.GetType()
                    .GetProperty(
                        "ВремяАккаунта");

            if (свойство != null)
            {
                var значение =
                    свойство.GetValue(
                        снимок);

                if (значение is TimeSpan время &&
                    время > TimeSpan.Zero)
                {
                    return время;
                }
            }

            var свойствоОсталось =
                снимок.GetType()
                    .GetProperty(
                        "Осталось");

            if (свойствоОсталось != null)
            {
                var значение =
                    свойствоОсталось.GetValue(
                        снимок);

                if (значение is TimeSpan остаток &&
                    остаток > TimeSpan.Zero)
                {
                    return остаток;
                }
            }

            return TimeSpan.Zero;
        }


