        private async void Голосовое_Click(
            object sender,
            RoutedEventArgs e)
        {
            if (приложениеЗакрывается)
            {
                return;
            }

            if (завершениеЗаписиГолосаВыполняется)
            {
                return;
            }

            if (записьГолосаИдёт)
            {
                ОстановитьЗаписьГолоса();

                return;
            }

            var подключение =
                ПолучитьВыбранныйПК();

            if (подключение == null)
            {
                return;
            }

            try
            {
                ОсвободитьОбъектыЗаписи();

                компьютерГолосаId =
                    подключение.КомпьютерId;

                потокГолоса =
                    new MemoryStream();

                писательГолоса =
                    new WaveFileWriter(
                        потокГолоса,
                        new WaveFormat(
                            16000,
                            16,
                            1));

                записьГолоса =
                    new WaveIn
                    {
                        WaveFormat =
                            new WaveFormat(
                                16000,
                                16,
                                1),

                        BufferMilliseconds =
                            50
                    };

                записьГолоса.DataAvailable +=
                    ЗаписьГолоса_DataAvailable;

                записьГолоса.RecordingStopped +=
                    ЗаписьГолоса_RecordingStopped;

                записьГолосаИдёт =
                    true;

                if (КнопкаГолосовое != null)
                {
                    КнопкаГолосовое.Content =
                        "⏹ Остановить запись";
                }

                ТекстСостояния.Text =
                    $"🎤 Идёт запись для ПК-{компьютерГолосаId}... Нажми ещё раз для отправки.";

                записьГолоса.StartRecording();
            }
            catch (Exception ошибка)
            {
                записьГолосаИдёт =
                    false;

                компьютерГолосаId =
                    null;

                ОсвободитьОбъектыЗаписи();

                if (КнопкаГолосовое != null)
                {
                    КнопкаГолосовое.Content =
                        "🎤 Записать голос";
                }

                ПоказатьОшибкаГолоса(
                    ошибка);
            }

            await Task.CompletedTask;
        }


