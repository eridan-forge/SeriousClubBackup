        private async void ЗаписьГолоса_RecordingStopped(
            object? sender,
            StoppedEventArgs args)
        {
            if (завершениеЗаписиГолосаВыполняется)
            {
                return;
            }

            завершениеЗаписиГолосаВыполняется =
                true;

            записьГолосаИдёт =
                false;

            if (КнопкаГолосовое != null &&
                !приложениеЗакрывается)
            {
                Dispatcher.Invoke(
                    () =>
                    {
                        КнопкаГолосовое.Content =
                            "🎤 Обработка...";
                    });
            }

            try
            {
                if (args.Exception != null)
                {
                    throw args.Exception;
                }

                писательГолоса?.Flush();

                var audio =
                    потокГолоса?.ToArray();

                if (audio == null ||
                    audio.Length == 0)
                {
                    if (!приложениеЗакрывается)
                    {
                        Dispatcher.Invoke(
                            () =>
                            {
                                ТекстСостояния.Text =
                                    "Голосовая запись пустая.";
                            });
                    }

                    return;
                }

                if (приложениеЗакрывается)
                {
                    return;
                }

                var base64 =
                    Convert.ToBase64String(
                        audio);

                var компьютерId =
                    компьютерГолосаId;

                if (!компьютерId.HasValue)
                {
                    Dispatcher.Invoke(
                        () =>
                        {
                            ТекстСостояния.Text =
                                "Не выбран ПК для голосового сообщения.";
                        });

                    return;
                }

                var успешно =
                    await ОтправитьГолосовоеAsync(
                        base64,
                        компьютерId.Value);

                if (!приложениеЗакрывается)
                {
                    Dispatcher.Invoke(
                        () =>
                        {
                            ТекстСостояния.Text =
                                успешно
                                    ? $"🎤 Голосовое отправлено на ПК-{компьютерId.Value}."
                                    : "Не удалось отправить голосовое.";
                        });
                }
            }
            catch (Exception ошибка)
            {
                if (!приложениеЗакрывается)
                {
                    Dispatcher.Invoke(
                        () =>
                        {
                            ПоказатьОшибкаГолоса(
                                ошибка);
                        });
                }
            }
            finally
            {
                ОсвободитьОбъектыЗаписи();

                компьютерГолосаId =
                    null;

                завершениеЗаписиГолосаВыполняется =
                    false;

                if (!приложениеЗакрывается &&
                    КнопкаГолосовое != null)
                {
                    Dispatcher.Invoke(
                        () =>
                        {
                            КнопкаГолосовое.Content =
                                "🎤 Записать голос";
                        });
                }
            }
        }


