                () =>
                {
                    try
                    {
                        var аккаунты =
                            new СервисАккаунтов();

                        var окончание =
                            DateTime.Now;

                        foreach (
                            var x
                            in снимок.Сеансы.ToList())
                        {
                            var начало =
                                ПолучитьНачалоИзСнимка(
                                    x);

                            var пауза =
                                ПолучитьВремяПаузыИзСнимка(
                                    x);

                            var сыграно =
                                окончание -
                                начало -
                                пауза;

                            if (сыграно < TimeSpan.Zero)
                            {
                                сыграно =
                                    TimeSpan.Zero;
                            }

                            var возвращено =
                                ПолучитьОстатокНаАккаунтИзСнимка(
                                    x);

                            var аккаунтId =
                                ПолучитьАккаунтИзСнимка(
                                    x);

                            if (аккаунтId.HasValue &&
                                возвращено > TimeSpan.Zero)
                            {
                                аккаунты.ДобавитьВремя(
                                    аккаунтId.Value,
                                    возвращено);
                            }

                            архив.Добавить(
                                new ЗаписьАварии005
                                {
                                    КомпьютерId =
                                        ПолучитьКомпьютерIdИзСнимка(
                                            x),

                                    Игрок =
