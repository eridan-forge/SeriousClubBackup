        private static Guid?
            ПолучитьАккаунтИзСнимка(
                object снимок)
        {
            if (снимок == null)
            {
                return null;
            }

            var свойство =
                снимок.GetType()
                    .GetProperty(
                        "АккаунтGuid");

            if (свойство == null)
            {
                return null;
            }

            var значение =
                свойство.GetValue(
                    снимок);

            if (значение is Guid guid)
            {
                return guid;
            }

            if (значение is string строка &&
                Guid.TryParse(
                    строка,
                    out var parsed))
            {
                return parsed;
            }

            return null;
        }


