        private void ПроверитьМёртвыеПК()
        {
            if (приложениеЗакрывается)
            {
                return;
            }

            foreach (
                var запись
                in подключения.Values.ToList())
            {
                if (DateTime.Now -
                    запись.ПоследнийСигнал <
                    TimeSpan.FromSeconds(5))
                {
                    continue;
                }

                if (!подключения.TryGetValue(
                        запись.КомпьютерId,
                        out var текущее) ||
                    !ReferenceEquals(
                        текущее,
                        запись))
                {
                    continue;
                }

                подключения.Remove(
                    запись.КомпьютерId);

                ОбновитьКарточку(
                    запись.КомпьютерId,
                    "Отключён",
                    Color.FromRgb(
                        127,
                        29,
                        29));

                TекстСостоянияБезопасно(
                    $"ПК-{запись.КомпьютерId} потерян.");

                var сеанс =
                    сервисСеансов
                        .ПолучитьАктивные()
                        .FirstOrDefault(
                            x =>
                                x.КомпьютерId ==
                                запись.КомпьютерId);

                if (сеанс != null)
                {
                    new СервисАвтоСохранения001()
                        .Сохранить(
                            сервисСеансов
                                .ПолучитьАктивные());
                }
            }

            ОбновитьКоличествоПК();
        }


