        private void ЗагрузитьСохранённыеСеансы()
        {
            var снимок =
                new СервисАвтоСохранения001()
                    .Загрузить();

            if (снимок == null ||
                снимок.Сеансы.Count == 0)
            {
                return;
            }

            var окно =
                new Окна.ОкноВосстановления004(
                    снимок)
                {
                    Owner = this
                };

            var архив =
                new СервисАрхива005();

            var снимокСервис =
                new СервисАвтоСохранения001();


            // -----------------------------------------------------
            // ВОЗОБНОВИТЬ
            // -----------------------------------------------------

            окно.Возобновить +=
                сеанс =>
                {
                    var id =
                        ПолучитьIdИзСнимка(
                            сеанс);

                    var сохранённый =
                        снимок.Сеансы
                            .FirstOrDefault(
                                x =>
                                    ПолучитьIdИзСнимка(x) ==
                                    id);

                    if (сохранённый == null)
                    {
                        return;
                    }

                    try
                    {
                        сервисСеансов
                            .ВосстановитьСеанс(
                                сохранённый);

                        снимок.Сеансы.RemoveAll(
                            x =>
                                ПолучитьIdИзСнимка(x) ==
                                id);

                        снимокСервис.Сохранить(
                            сервисСеансов
                                .ПолучитьАктивные());

                        ТекстСостояния.Text =
                            $"Возобновлён {ПолучитьИмяИзСнимка(сеанс)}.";
                    }
                    catch (Exception ошибка)
                    {
                        MessageBox.Show(
                            ошибка.Message,
                            "Ошибка восстановления",
                            MessageBoxButton.OK,
                            MessageBoxImage.Error);
                    }
                };


            // -----------------------------------------------------
            // ЗАВЕРШИТЬ ОДИН
            // -----------------------------------------------------

            окно.Завершить +=
                сеанс =>
                {
                    try
                    {
                        var окончание =
                            DateTime.Now;

                        var начало =
                            ПолучитьНачалоИзСнимка(
                                сеанс);

                        var пауза =
                            ПолучитьВремяПаузыИзСнимка(
                                сеанс);

                        var сыграно =
                            окончание -
                            начало -
                            пауза;

                        if (сыграно < TimeSpan.Zero)
                        {
                            сыграно =
                                TimeSpan.Zero;
                        }

                        var возвращено =
                            ПолучитьОстатокНаАккаунтИзСнимка(
                                сеанс);

                        var аккаунтId =
                            ПолучитьАккаунтИзСнимка(
                                сеанс);

                        if (аккаунтId.HasValue &&
                            возвращено > TimeSpan.Zero)
                        {
                            var сервисАккаунтов =
                                new СервисАккаунтов();

                            сервисАккаунтов
                                .ДобавитьВремя(
                                    аккаунтId.Value,
                                    возвращено);
                        }

                        архив.Добавить(
                            new ЗаписьАварии005
                            {
                                КомпьютерId =
                                    ПолучитьКомпьютерIdИзСнимка(
                                        сеанс),

                                Игрок =
                                    ПолучитьИмяИзСнимка(
                                        сеанс),

                                АккаунтGuid =
                                    аккаунтId,

                                Начало =
                                    начало,

                                Отключение =
                                    окончание,

                                Сыграно =
                                    сыграно,

                                Возвращено =
                                    возвращено,

                                Стоимость =
                                    ПолучитьСтоимостьИзСнимка(
                                        сеанс),

                                Причина =
                                    "Завершено при восстановлении"
                            });

                        var id =
                            ПолучитьIdИзСнимка(
                                сеанс);

                        снимок.Сеансы.RemoveAll(
                            x =>
                                ПолучитьIdИзСнимка(x) ==
                                id);

                        снимокСервис.Сохранить(
                            сервисСеансов
                                .ПолучитьАктивные());

                        ТекстСостояния.Text =
                            $"{ПолучитьИмяИзСнимка(сеанс)} завершён.";
                    }
                    catch (Exception ошибка)
                    {
                        MessageBox.Show(
                            ошибка.Message,
                            "Ошибка завершения",
                            MessageBoxButton.OK,
                            MessageBoxImage.Error);
                    }
                };


            // -----------------------------------------------------
