using System;
using System.Collections.Generic;
using System.Linq;
using серьёзный.Модели;

namespace серьёзный.Сервисы
{
    public class СервисФинансов
    {
        private readonly List<ФинансоваяОперация> операции = new();

        private long следующийId = 1;

        public IReadOnlyList<ФинансоваяОперация> ПолучитьВсеОперации()
        {
            return операции;
        }

        public ФинансоваяОперация ДобавитьОплату(
            decimal сумма,
            int? сеансId = null,
            string комментарий = "")
        {
            return Добавить(
                ТипФинансовойОперации.Оплата,
                сумма,
                "Оплата игрового сеанса",
                сеансId,
                комментарий);
        }

        public ФинансоваяОперация ДобавитьВозврат(
            decimal сумма,
            int? сеансId = null,
            string комментарий = "")
        {
            return Добавить(
                ТипФинансовойОперации.Возврат,
                -Math.Abs(сумма),
                "Возврат клиенту",
                сеансId,
                комментарий);
        }

        public ФинансоваяОперация ДобавитьКорректировкуПлюс(
            decimal сумма,
            string причина,
            string комментарий = "")
        {
            return Добавить(
                ТипФинансовойОперации.КорректировкаПлюс,
                Math.Abs(сумма),
                причина,
                null,
                комментарий);
        }

        public ФинансоваяОперация ДобавитьКорректировкуМинус(
            decimal сумма,
            string причина,
            string комментарий = "")
        {
            return Добавить(
                ТипФинансовойОперации.КорректировкаМинус,
                -Math.Abs(сумма),
                причина,
                null,
                комментарий);
        }

        public decimal ПолучитьИтог()
        {
            return операции.Sum(x => x.Сумма);
        }

        private ФинансоваяОперация Добавить(
            ТипФинансовойОперации тип,
            decimal сумма,
            string причина,
            int? сеансId,
            string комментарий)
        {
            var операция = new ФинансоваяОперация
            {
                Id = следующийId++,
                Дата = DateTime.Now,
                Тип = тип,
                Сумма = сумма,
                Причина = причина,
                СеансId = сеансId,
                Комментарий = комментарий
            };

            операции.Add(операция);

            return операция;
        }
    }
}