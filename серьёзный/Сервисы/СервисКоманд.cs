using System.Threading.Tasks;
using серьёзный.Сеть;

namespace серьёзный.Сервисы
{
    public class СервисКоманд
    {
        private readonly СерверСвязи сервер;

        public СервисКоманд(
            СерверСвязи сервер)
        {
            this.сервер = сервер;
        }

        public async Task<bool> ОтправитьAsync(
            int компьютерId,
            КомандаПатрулю команда)
        {
            var подключение =
                сервер.ПолучитьПодключение(
                    компьютерId);

            if (подключение == null)
                return false;

            if (!подключение.Подключено)
                return false;

            var сообщение =
                СетевоеСообщение.Создать(
                    ТипСообщения.Команда);

            сообщение.КомпьютерId =
                компьютерId;

            сообщение.УстановитьДанные(
                команда);

            return await подключение
                .ОтправитьAsync(сообщение);
        }
    }
}