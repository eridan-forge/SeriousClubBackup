using System;
using System.Collections.Generic;
using System.Linq;
using серьёзный.Модели;
using серьёзный.Сеть;

namespace серьёзный.Сервисы
{
    public class СервисСостоянияСети
    {
        private readonly СервисКомпьютеров
            сервисКомпьютеров;

        private readonly СервисИстории
            сервисИстории;

        public СервисСостоянияСети(
            СервисКомпьютеров сервисКомпьютеров,
            СервисИстории сервисИстории)
        {
            this.сервисКомпьютеров =
                сервисКомпьютеров;

            this.сервисИстории =
                сервисИстории;
        }

        public void ПатрульПодключился(
            ПодключениеПатруля подключение)
        {
            var компьютер =
                сервисКомпьютеров
                    .ПолучитьПоId(
                        подключение.КомпьютерId);

            if (компьютер == null)
                return;

            компьютер.НаСвязи = true;

            компьютер.Включен = true;

            компьютер.Состояние =
                СостояниеКомпьютера.Свободен;

            компьютер.ПоследнийКонтакт =
                DateTime.Now;

            сервисИстории.Добавить(
                "Подключение",
                $"Патруль {компьютер.Имя} подключён",
                компьютер.Id);
        }

        public void ПатрульОтключился(
            ПодключениеПатруля подключение)
        {
            var компьютер =
                сервисКомпьютеров
                    .ПолучитьПоId(
                        подключение.КомпьютерId);

            if (компьютер == null)
                return;

            компьютер.НаСвязи = false;

            компьютер.Состояние =
                СостояниеКомпьютера.НетСвязи;

            компьютер.ПоследнийКонтакт =
                DateTime.Now;

            сервисИстории.Добавить(
                "Отключение",
                $"Патруль {компьютер.Имя} потерял связь",
                компьютер.Id);
        }

        public void ОбработатьHeartbeat(
            ПодключениеПатруля подключение)
        {
            var компьютер =
                сервисКомпьютеров
                    .ПолучитьПоId(
                        подключение.КомпьютерId);

            if (компьютер == null)
                return;

            компьютер.НаСвязи = true;

            компьютер.ПоследнийКонтакт =
                DateTime.Now;
        }

        public void ОбработатьСостояние(
            СетевоеСообщение сообщение)
        {
            var состояние =
                сообщение
                    .ПолучитьДанные<
                        СостояниеПатруля>();

            if (состояние == null)
                return;

            var компьютер =
                сервисКомпьютеров
                    .ПолучитьПоId(
                        состояние.КомпьютерId);

            if (компьютер == null)
                return;

            компьютер.НаСвязи = true;

            компьютер.Включен =
                состояние.WindowsЗапущен;

            компьютер.ПоследнийКонтакт =
                DateTime.Now;

            компьютер.ТекущийСеансId =
                состояние.СеансId;

            if (состояние.ПользовательЗаблокирован)
            {
                компьютер.Состояние =
                    СостояниеКомпьютера.Заблокирован;
            }
            else if (состояние.СеансАктивен)
            {
                компьютер.Состояние =
                    СостояниеКомпьютера.Занят;
            }
            else
            {
                компьютер.Состояние =
                    СостояниеКомпьютера.Свободен;
            }
        }
    }
}