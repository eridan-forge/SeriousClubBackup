using System;
using System.Collections.Generic;
using System.Linq;
using серьёзный.Модели;

namespace серьёзный.Сервисы
{
    public class СервисОтчётов
    {
        private readonly СервисСеансов сервисСеансов;
        private readonly СервисФинансов сервисФинансов;

        public СервисОтчётов(
            СервисСеансов сервисСеансов,
            СервисФинансов сервисФинансов)
        {
            this.сервисСеансов = сервисСеансов;
            this.сервисФинансов = сервисФинансов;
        }

        public Отчёт Сформировать(
            DateTime начало,
            DateTime конец)
        {
            var сеансы = сервисСеансов
                .ПолучитьВсе()
                .Where(x =>
                    x.Начало >= начало &&
                    x.Начало <= конец)
                .ToList();

            var операции = сервисФинансов
                .ПолучитьВсеОперации()
                .Where(x =>
                    x.Дата >= начало &&
                    x.Дата <= конец)
                .ToList();

            return new Отчёт
            {
                НачалоПериода = начало,
                КонецПериода = конец,

                КоличествоСеансов = сеансы.Count,

                ОбщееИгровоеВремя = РассчитатьИгровоеВремя(сеансы),

                Выручка = операции
                    .Where(x =>
                        x.Тип == ТипФинансовойОперации.Оплата)
                    .Sum(x => x.Сумма),

                Возвраты = Math.Abs(
                    операции
                        .Where(x =>
                            x.Тип == ТипФинансовойОперации.Возврат)
                        .Sum(x => x.Сумма)),

                Корректировки = операции
                    .Where(x =>
                        x.Тип == ТипФинансовойОперации.КорректировкаПлюс ||
                        x.Тип == ТипФинансовойОперации.КорректировкаМинус)
                    .Sum(x => x.Сумма)
            };
        }

        private static TimeSpan РассчитатьИгровоеВремя(
            IEnumerable<Сеанс> сеансы)
        {
            var итог = TimeSpan.Zero;

            foreach (var сеанс in сеансы)
            {
                var конец = сеанс.ФактическоеОкончание
                    ?? сеанс.ЗапланированноеОкончание;

                if (конец > сеанс.Начало)
                    итог += конец - сеанс.Начало;
            }

            return итог;
        }
    }
}