using System.Text.Json;
using System.Threading.Tasks;
using серьёзный.Сеть;

namespace серьёзный.Сервисы
{
    public class СервисКомандПК
    {
        private readonly СерверСвязи
            серверСвязи;

        public СервисКомандПК(
            СерверСвязи серверСвязи)
        {
            this.серверСвязи =
                серверСвязи;
        }

        public Task<bool> Заблокировать(
            int компьютерId)
        {
            return Отправить(
                компьютерId,
                КомандаПК.Заблокировать);
        }

        public Task<bool> Разблокировать(
            int компьютерId)
        {
            return Отправить(
                компьютерId,
                КомандаПК.Разблокировать);
        }

        public Task<bool> Перезагрузить(
            int компьютерId)
        {
            return Отправить(
                компьютерId,
                КомандаПК.Перезагрузить);
        }

        public Task<bool> Выключить(
            int компьютерId)
        {
            return Отправить(
                компьютерId,
                КомандаПК.Выключить);
        }

        public Task<bool> ПоказатьУведомление(
            int компьютерId,
            string текст)
        {
            return Отправить(
                компьютерId,
                КомандаПК.ПоказатьУведомление,
                new КомандаПатрулю
                {
                    Команда =
                        КомандаПК.ПоказатьУведомление,

                    Текст = текст
                });
        }

        public Task<bool> ВоспроизвестиГолосовое(
            int компьютерId,
            string файл)
        {
            return Отправить(
                компьютерId,
                КомандаПК.ВоспроизвестиГолосовое,
                new КомандаПатрулю
                {
                    Команда =
                        КомандаПК.ВоспроизвестиГолосовое,

                    Файл = файл
                });
        }

        public Task<bool> ЗавершитьСеанс(
            int компьютерId,
            int сеансId)
        {
            return Отправить(
                компьютерId,
                КомандаПК.ЗавершитьСеанс,
                new КомандаПатрулю
                {
                    Команда =
                        КомандаПК.ЗавершитьСеанс,

                    СеансId = сеансId
                });
        }

        private async Task<bool> Отправить(
            int компьютерId,
            КомандаПК команда,
            КомандаПатрулю? данные = null)
        {
            var подключение =
                серверСвязи
                    .ПолучитьПодключение(
                        компьютерId);

            if (подключение == null)
                return false;

            var сообщение =
                СетевоеСообщение.Создать(
                    ТипСообщения.Команда);

            сообщение.КомпьютерId =
                компьютерId;

            var командаПатрулю =
                данные ??
                new КомандаПатрулю
                {
                    Команда = команда
                };

            сообщение.УстановитьДанные(
                командаПатрулю);

            return await подключение
                .ОтправитьAsync(сообщение);
        }
    }
}