                if (сеанс == null)
                {
                    return false;
                }

                ЗавершитьИАрхивировать(
                    сеанс,
                    причина);

                автосохранение.Сохранить(
                    ПолучитьАктивныеВнутри());

                return true;
            }
        }


        // =========================================================
        // ТАЙМЕР
        // =========================================================

        public void Запустить()
        {
            Остановить();

            таймер =
                new System.Threading.Timer(
                    _ =>
                    {
                        try
                        {
                            ПроверитьИстёкшиеСеансы();
                        }
                        catch
                        {
                        }
                    },
                    null,
                    1000,
                    1000);
        }


        public void Остановить()
        {
            таймер?.Dispose();
            таймер = null;
        }


