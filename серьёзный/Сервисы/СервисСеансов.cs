        // ВАЖНО: НЕ храним долгоживущий экземпляр СервисАккаунтов.
        // Он кэширует список аккаунтов в памяти только на момент
        // создания и никогда не перечитывает базу. Если админ
        // создаёт новый аккаунт после запуска сервера (обычный
        // сценарий), этот кэш его не видит — из-за этого баланс
        // не подключался к сеансу и не возвращался при завершении,
        // а вход в аккаунт на Экране Клуба выдавал "неверный пароль".
        // Поэтому создаём свежий экземпляр перед каждым обращением.
        private static СервисАккаунтов Аккаунты() => new();

        private int следующийId = 1;

        private System.Threading.Timer? таймер;

