        public decimal ТекущаяВыручка
        {
            get
            {
                lock (синхронизация)
                {
                    return
                        архив
                            .ПолучитьВсе()
                            .Where(x =>
                                x.Отключение.Date ==
                                DateTime.Today)
                            .Sum(x =>
                                x.Стоимость)
                        +
                        сеансы
                            .Where(x =>
                                x.Статус ==
                                    СтатусСеанса.Активен ||
                                x.Статус ==
                                    СтатусСеанса.НаПаузе)
                            .Sum(x =>
                                x.Стоимость);
                }
            }
        }


        public int СеансовСегодня
        {
            get
            {
                lock (синхронизация)
                {
                    return
                        архив
                            .ПолучитьВсе()
                            .Count(x =>
                                x.Отключение.Date ==
                                DateTime.Today);
                }
            }
        }


        public TimeSpan ИгровоеВремяСегодня
        {
            get
            {
                lock (синхронизация)
                {
                    return
                        архив
                            .ПолучитьВсе()
                            .Where(x =>
                                x.Отключение.Date ==
                                DateTime.Today)
                            .Aggregate(
                                TimeSpan.Zero,
                                (итог, x) =>
                                    итог +
                                    x.Сыграно);
                }
            }
        }


        public decimal СреднийЧек
        {
            get
            {
                lock (синхронизация)
                {
                    var завершённые =
                        архив
                            .ПолучитьВсе()
                            .Where(x =>
                                x.Отключение.Date ==
                                DateTime.Today)
                            .ToList();

                    if (завершённые.Count == 0)
                    {
                        return 0;
                    }

                    return завершённые.Average(
                        x => x.Стоимость);
                }
            }
        }


        public int АктивныхСеансов
        {
            get
            {
                lock (синхронизация)
                {
                    return
                        сеансы.Count(x =>
                            x.Статус ==
                                СтатусСеанса.Активен ||
                            x.Статус ==
                                СтатусСеанса.НаПаузе);
                }
            }
        }


        // =========================================================
        // ЗАВЕРШИТЬ ПО КОМПЬЮТЕРУ
        // =========================================================

        public bool ЗавершитьПоКомпьютеру(
            int компьютерId,
            string причина)
        {
            lock (синхронизация)
            {
                var сеанс =
