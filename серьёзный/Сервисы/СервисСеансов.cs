        // =========================================================
        // ДОБАВИТЬ ВРЕМЯ АКТИВНОМУ СЕАНСУ
        // =========================================================

        public bool ДобавитьВремяСеансу(
            int компьютерId,
            TimeSpan время)
        {
            if (время <=
                TimeSpan.Zero)
            {
                return false;
            }

            lock (синхронизация)
            {
                var сеанс =
                    ПолучитьАктивныйПоКомпьютеруВнутри(
                        компьютерId);

                if (сеанс == null)
                {
                    return false;
                }

                var сейчас =
                    DateTime.Now;

                if (сеанс.ЗапланированноеОкончание < сейчас)
                {
                    сеанс.ЗапланированноеОкончание =
                        сейчас;
                }

                сеанс.ЗапланированноеОкончание +=
                    время;

                сеанс.КупленноеВремя +=
                    время;

                if (сеанс.АккаунтGuid.HasValue &&
                    сеанс.ИспользуетсяОстатокАккаунта &&
                    сеанс.Режим ==
                        РежимВремени.ТолькоБаланс)
                {
                    сеанс.Режим =
                        РежимВремени.БалансПлюсПокупное;
                }

                база.Сохранить(
                    сеанс);

                автосохранение.Сохранить(
                    ПолучитьАктивныеВнутри());

                СеансОбновился?.Invoke(
                    сеанс);

                return true;
            }
        }


        // =========================================================
        // УБАВИТЬ ВРЕМЯ
        // =========================================================

        public bool УбавитьВремяСеансу(
            int компьютерId,
            TimeSpan время)
        {
            if (время <=
                TimeSpan.Zero)
            {
                return false;
            }

            lock (синхронизация)
            {
                var сеанс =
                    ПолучитьАктивныйПоКомпьютеруВнутри(
                        компьютерId);

                if (сеанс == null)
                {
                    return false;
                }

                var осталось =
                    сеанс.ОсталосьВремени;

                if (осталось <=
                    TimeSpan.Zero)
                {
                    return false;
                }

                if (время >= осталось)
                {
                    return false;
                }

                var осталосьУбрать =
                    время;

                if (сеанс.КупленноеВремя >
                    TimeSpan.Zero)
                {
                    var изПокупки =
                        TimeSpan.FromTicks(
                            Math.Min(
                                сеанс.КупленноеВремя.Ticks,
                                осталосьУбрать.Ticks));

                    сеанс.КупленноеВремя -=
                        изПокупки;

                    осталосьУбрать -=
                        изПокупки;
                }

                if (осталосьУбрать >
                        TimeSpan.Zero &&
                    сеанс.ВремяАккаунта >
                        TimeSpan.Zero)
                {
                    var изБаланса =
                        TimeSpan.FromTicks(
                            Math.Min(
                                сеанс.ВремяАккаунта.Ticks,
                                осталосьУбрать.Ticks));

                    сеанс.ВремяАккаунта -=
                        изБаланса;

                    осталосьУбрать -=
                        изБаланса;

                    if (сеанс.АккаунтGuid.HasValue)
                    {
                        Аккаунты().УстановитьОстаток(
                            сеанс.АккаунтGuid.Value,
                            сеанс.ВремяАккаунта);
                    }
                }

                сеанс.ЗапланированноеОкончание -=
                    время;

                var минимум =
                    DateTime.Now.AddSeconds(1);

                if (сеанс.ЗапланированноеОкончание < минимум)
                {
                    сеанс.ЗапланированноеОкончание =
                        минимум;
                }

                if (сеанс.КупленноеВремя <=
                        TimeSpan.Zero &&
                    сеанс.АккаунтGuid.HasValue &&
                    сеанс.ВремяАккаунта >
                        TimeSpan.Zero)
                {
                    сеанс.Режим =
                        РежимВремени.ТолькоБаланс;
                }

                база.Сохранить(
                    сеанс);

                автосохранение.Сохранить(
