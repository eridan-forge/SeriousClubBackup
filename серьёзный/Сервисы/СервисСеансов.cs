            }
        }


        // =========================================================
        // НАЧАЛО СЕАНСА
        // =========================================================

        public Сеанс НачатьСеанс(
            int компьютерId,
            int? клиентId,
            string имяКлиента,
            TimeSpan продолжительность,
            decimal стоимость)
        {
            if (продолжительность <=
                TimeSpan.Zero)
            {
                throw new ArgumentOutOfRangeException(
                    nameof(продолжительность));
            }

            lock (синхронизация)
            {
                if (ПолучитьАктивныйПоКомпьютеруВнутри(
                        компьютерId) != null)
                {
                    throw new InvalidOperationException(
                        "На этом компьютере уже идёт сеанс.");
                }

                var сейчас =
                    DateTime.Now;

                var сеанс =
                    new Сеанс
                    {
                        Id =
                            следующийId++,

                        КомпьютерId =
                            компьютерId,

                        КлиентId =
                            клиентId,

                        ИмяКлиента =
                            string.IsNullOrWhiteSpace(
                                имяКлиента)
                                ? "Аноним"
                                : имяКлиента.Trim(),

                        Начало =
                            сейчас,

                        ЗапланированноеОкончание =
                            сейчас +
                            продолжительность,

                        Стоимость =
                            Math.Max(
                                0m,
                                стоимость),

                        Статус =
                            СтатусСеанса.Активен,

                        КупленноеВремя =
                            продолжительность,

                        ВремяАккаунта =
                            TimeSpan.Zero,

                        ИсходноеВремяАккаунта =
                            TimeSpan.Zero,

                        ИспользуетсяОстатокАккаунта =
                            false,

                        Режим =
                            РежимВремени.ТолькоПокупное,

                        ПоследнееОбновление =
                            сейчас
                    };

                сеансы.Add(
                    сеанс);

                база.Сохранить(
                    сеанс);

                СеансОбновился?.Invoke(
                    сеанс);

                СеансНачался?.Invoke(
                                   сеанс);
                return сеанс;

            }
        }


        // =========================================================
        // ВОССТАНОВЛЕНИЕ
        // =========================================================

        public Сеанс ВосстановитьСеанс(
            Сеанс001 снимок)
        {
            lock (синхронизация)
            {
                var купленное =
                    снимок.КупленноеВремя;

                if (купленное < TimeSpan.Zero)
                {
                    купленное =
                        TimeSpan.Zero;
                }

                var баланс =
                    снимок.ВремяАккаунта;

                if (баланс < TimeSpan.Zero)
                {
                    баланс =
                        TimeSpan.Zero;
                }

                var сеанс =
                    new Сеанс
                    {
                        Id =
                            снимок.Id,

                        КомпьютерId =
                            снимок.КомпьютерId,

                        КлиентId =
                            null,

                        ИмяКлиента =
                            string.IsNullOrWhiteSpace(
                                снимок.ИмяКлиента)
                                ? "Аноним"
                                : снимок.ИмяКлиента,

                        Начало =
                            снимок.Начало,

                        ЗапланированноеОкончание =
                            DateTime.Now +
                            баланс +
                            купленное,

                        Стоимость =
                            Math.Max(
                                0m,
                                снимок.Стоимость),

                        Статус =
                            СтатусСеанса.Активен,

                        АккаунтGuid =
                            снимок.АккаунтGuid,

                        КупленноеВремя =
                            купленное,

                        ВремяАккаунта =
                            баланс,

                        ИсходноеВремяАккаунта =
                            баланс,

                        ИспользуетсяОстатокАккаунта =
                            снимок.ИспользуетсяОстатокАккаунта,

                        ПоследнееОбновление =
                            DateTime.Now
                    };

                if (сеанс.ИспользуетсяОстатокАккаунта)
                {
                    сеанс.Режим =
                        купленное > TimeSpan.Zero
                            ? РежимВремени.БалансПлюсПокупное
                            : РежимВремени.ТолькоБаланс;
                }
                else
                {
                    сеанс.Режим =
                        РежимВремени.ТолькоПокупное;
                }

                сеансы.RemoveAll(
                    x =>
                        x.КомпьютерId ==
                        снимок.КомпьютерId);

                сеансы.Add(
                    сеанс);

                if (сеанс.Id >= следующийId)
                {
                    следующийId =
                        сеанс.Id + 1;
                }

                база.Сохранить(
                    сеанс);

                СеансОбновился?.Invoke(
                    сеанс);

                return сеанс;
            }
        }


        // =========================================================
        // ПРОДЛЕНИЕ СЕАНСА
        // =========================================================

        public bool ПродлитьСеанс(
            int сеансId,
            TimeSpan дополнительноеВремя,
            decimal дополнительнаяСтоимость)
        {
            if (дополнительноеВремя <=
                TimeSpan.Zero)
            {
                return false;
            }

            return ДобавитьВремяВнутри(
                сеансId,
                дополнительноеВремя,
                дополнительнаяСтоимость);
        }


        private bool ДобавитьВремяВнутри(
            int сеансId,
            TimeSpan дополнительноеВремя,
            decimal дополнительнаяСтоимость)
        {
            lock (синхронизация)
            {
                var сеанс =
                    ПолучитьАктивныйПоIdВнутри(
                        сеансId);

                if (сеанс == null)
                {
                    return false;
                }

                сеанс.ЗапланированноеОкончание +=
                    дополнительноеВремя;

                сеанс.КупленноеВремя +=
                    дополнительноеВремя;

                if (сеанс.АккаунтGuid.HasValue &&
                    сеанс.ИспользуетсяОстатокАккаунта &&
                    сеанс.Режим ==
                        РежимВремени.ТолькоБаланс)
                {
                    сеанс.Режим =
                        РежимВремени.БалансПлюсПокупное;
                }

                сеанс.Стоимость +=
                    дополнительнаяСтоимость;

                if (сеанс.Стоимость < 0m)
                {
                    сеанс.Стоимость =
                        0m;
                }

                база.Сохранить(
                    сеанс);

                автосохранение.Сохранить(
                    ПолучитьАктивныеВнутри());

                СеансОбновился?.Invoke(
                    сеанс);

                return true;
            }
        }


