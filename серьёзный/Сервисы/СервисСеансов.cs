        public IReadOnlyList<Сеанс> ПолучитьВсе()
        {
            lock (синхронизация)
            {
                return
                    сеансы.ToList();
            }
        }


        public IReadOnlyList<Сеанс> ПолучитьАктивные()
        {
            lock (синхронизация)
            {
                return
                    ПолучитьАктивныеВнутри();
            }
        }


        private List<Сеанс> ПолучитьАктивныеВнутри()
        {
            return
                сеансы
                    .Where(x =>
                        x.Статус ==
                            СтатусСеанса.Активен ||
                        x.Статус ==
                            СтатусСеанса.НаПаузе)
                    .ToList();
        }


        public Сеанс? ПолучитьПоId(
            int id)
        {
            lock (синхронизация)
            {
                return
                    сеансы.FirstOrDefault(
