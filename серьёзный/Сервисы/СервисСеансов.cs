        // =========================================================
        // ЗАВЕРШЕНИЕ И АРХИВАЦИЯ
        // =========================================================

        private void ЗавершитьИАрхивировать(
            Сеанс сеанс,
            string причина)
        {
            if (сеанс.Статус != СтатусСеанса.Активен &&
                сеанс.Статус != СтатусСеанса.НаПаузе)
            {
                return;
            }

            var окончание =
                DateTime.Now;

            var итоговаяПауза =
                сеанс.ВремяПаузы;

            if (сеанс.Статус == СтатусСеанса.НаПаузе &&
                сеанс.НачалоПаузы.HasValue)
            {
                итоговаяПауза +=
                    окончание -
                    сеанс.НачалоПаузы.Value;
            }

            var сыграно =
                окончание -
                сеанс.Начало -
                итоговаяПауза;

            if (сыграно < TimeSpan.Zero)
            {
                сыграно =
                    TimeSpan.Zero;
            }

            сеанс.ФактическоеОкончание =
                окончание;

            сеанс.ВремяПаузы =
                итоговаяПауза;

            сеанс.НачалоПаузы =
                null;

            // ВремяАккаунта уже было списано во время игры
            // (поминутно синхронизируется в Accounts.RemainingSeconds
            // через УстановитьОстаток в фоновом таймере).
            // Его здесь НЕ возвращаем.
            //
            // КупленноеВремя содержит только НЕИСПОЛЬЗОВАННУЮ
            // часть покупного времени. Поэтому именно её
            // можно вернуть на аккаунт.

            var возвращено =
                TimeSpan.Zero;

            if (сеанс.АккаунтGuid.HasValue)
            {
                if (сеанс.КупленноеВремя > TimeSpan.Zero)
                {
                    возвращено =
                        сеанс.КупленноеВремя;

                    Аккаунты().ДобавитьВремя(
                        сеанс.АккаунтGuid.Value,
                        возвращено);
                }

                Аккаунты().ЗавершитьСтатистику(
                    сеанс.АккаунтGuid.Value);
            }

            сеанс.КупленноеВремя =
                TimeSpan.Zero;

            сеанс.ВремяАккаунта =
                TimeSpan.Zero;

            сеанс.Статус =
                СтатусСеанса.Завершён;

            архив.Добавить(
                new ЗаписьАварии005
                {
                    КомпьютерId =
                        сеанс.КомпьютерId,

                    Игрок =
                        сеанс.ИмяКлиента,

                    АккаунтGuid =
                        сеанс.АккаунтGuid,

                    Начало =
                        сеанс.Начало,

                    Отключение =
                        окончание,

                    Сыграно =
                        сыграно,

                    Возвращено =
                        возвращено,

                    Стоимость =
                        сеанс.Стоимость,

                    Причина =
                        причина
                });

            база.Удалить(
                сеанс.Id);

            СеансЗавершился?.Invoke(
                сеанс);
        }


