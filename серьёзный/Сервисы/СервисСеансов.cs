        // =========================================================
        // ОСНОВНОЙ ТАЙМЕР
        // =========================================================

        public void ПроверитьИстёкшиеСеансы()
        {
            lock (синхронизация)
            {
                foreach (var сеанс in
                         сеансы
                             .Where(
                                 x =>
                                     x.Статус ==
                                     СтатусСеанса.Активен)
                             .ToList())
                {
                    var сейчас =
                        DateTime.Now;

                    var прошло =
                        сейчас -
                        сеанс.ПоследнееОбновление;

                    if (прошло < TimeSpan.Zero)
                    {
                        прошло =
                            TimeSpan.Zero;
                    }

                    if (прошло >
                        TimeSpan.FromMinutes(5))
                    {
                        прошло =
                            TimeSpan.FromMinutes(5);
                    }

                    сеанс.ПоследнееОбновление =
                        сейчас;

                    if (сеанс.АккаунтGuid.HasValue)
                    {
                        Аккаунты().ОбновитьВоВремяСеанса(
                            сеанс.АккаунтGuid.Value,
                            прошло,
                            false);
                    }

                    var осталосьПрошлого =
                        прошло;

                    if (сеанс.Режим ==
                            РежимВремени.ТолькоБаланс ||
                        сеанс.Режим ==
                            РежимВремени.БалансПлюсПокупное)
                    {
                        var изБаланса =
                            TimeSpan.FromTicks(
                                Math.Min(
                                    Math.Max(
                                        0,
                                        сеанс.ВремяАккаунта.Ticks),
                                    Math.Max(
                                        0,
                                        осталосьПрошлого.Ticks)));

                        if (изБаланса >
                            TimeSpan.Zero)
                        {
                            сеанс.ВремяАккаунта -=
                                изБаланса;

                            осталосьПрошлого -=
                                изБаланса;

                            if (сеанс.АккаунтGuid.HasValue)
                            {
                                Аккаунты().УстановитьОстаток(
                                    сеанс.АккаунтGuid.Value,
                                    сеанс.ВремяАккаунта);
                            }
                        }
                    }

                    if (осталосьПрошлого >
                        TimeSpan.Zero)
                    {
                        var изПокупного =
                            TimeSpan.FromTicks(
                                Math.Min(
                                    Math.Max(
                                        0,
                                        сеанс.КупленноеВремя.Ticks),
                                    Math.Max(
                                        0,
                                        осталосьПрошлого.Ticks)));

                        сеанс.КупленноеВремя -=
                            изПокупного;

                        осталосьПрошлого -=
                            изПокупного;
                    }

                    var суммарноОсталось =
                        сеанс.ВремяАккаунта +
                        сеанс.КупленноеВремя;

                    var ожидаемоеОкончание =
                        сейчас +
                        суммарноОсталось;

                    if (суммарноОсталось >
                        TimeSpan.Zero)
                    {
                        сеанс.ЗапланированноеОкончание =
                            ожидаемоеОкончание;
                    }
                    else
                    {
                        сеанс.ЗапланированноеОкончание =
                            сейчас;
                    }

                    var осталось =
                        сеанс.ОсталосьВремени;

                    if (!сеанс.Предупреждение15МинутОтправлено &&
                        осталось <=
                            TimeSpan.FromMinutes(15))
                    {
                        сеанс.Предупреждение15МинутОтправлено =
                            true;

                        Предупреждение15Минут?.Invoke(
                            сеанс);
                    }

                    if (!сеанс.Предупреждение10МинутОтправлено &&
                        осталось <=
                            TimeSpan.FromMinutes(10))
                    {
                        сеанс.Предупреждение10МинутОтправлено =
                            true;

                        Предупреждение10Минут?.Invoke(
                            сеанс);
                    }

                    if (!сеанс.Предупреждение5МинутОтправлено &&
                        осталось <=
                            TimeSpan.FromMinutes(5))
                    {
                        сеанс.Предупреждение5МинутОтправлено =
                            true;

                        Предупреждение5Минут?.Invoke(
                            сеанс);
                    }

                    if (сеанс.ВремяАккаунта <=
                            TimeSpan.Zero &&
                        сеанс.КупленноеВремя <=
                            TimeSpan.Zero)
                    {
                        ЗавершитьИАрхивировать(
                            сеанс,
                            "Время истекло");

                        continue;
                    }

                    база.Сохранить(
                        сеанс);

                    СеансОбновился?.Invoke(
                        сеанс);
                }

                автосохранение.Сохранить(
                    ПолучитьАктивныеВнутри());
            }
        }


        // =========================================================
        // ИСПОЛЬЗОВАТЬ ОСТАТОК АККАУНТА
        // =========================================================

        public void ИспользоватьОстаток(
            int компьютерId,
            Guid аккаунтId,
            TimeSpan остаток,
            bool добавитьКПокупке)
        {
            lock (синхронизация)
            {
                var сеанс =
                    ПолучитьАктивныйПоКомпьютеруВнутри(
                        компьютерId);

                if (сеанс == null)
                {
                    return;
                }

                var аккаунт =
                    Аккаунты().Все
                        .FirstOrDefault(
                            x =>
                                x.Id ==
                                аккаунтId);

                if (аккаунт == null)
                {
                    return;
                }

                var фактическийОстаток =
                    аккаунт.ОсталосьВремени;

                if (фактическийОстаток < TimeSpan.Zero)
                {
                    фактическийОстаток =
                        TimeSpan.Zero;
                }

                сеанс.АккаунтGuid =
                    аккаунт.Id;

                сеанс.ИсходноеВремяАккаунта =
                    фактическийОстаток;

                сеанс.ВремяАккаунта =
                    фактическийОстаток;

                сеанс.ИспользуетсяОстатокАккаунта =
                    true;

                if (добавитьКПокупке)
                {
                    сеанс.Режим =
                        РежимВремени.БалансПлюсПокупное;
                }
                else
                {
                    сеанс.Режим =
                        РежимВремени.ТолькоБаланс;

                    сеанс.КупленноеВремя =
                        TimeSpan.Zero;
                }

                сеанс.ЗапланированноеОкончание =
                    DateTime.Now +
                    сеанс.ВремяАккаунта +
                    сеанс.КупленноеВремя;

                сеанс.ПоследнееОбновление =
                    DateTime.Now;

                база.Сохранить(
                    сеанс);

                автосохранение.Сохранить(
                    ПолучитьАктивныеВнутри());

                СеансОбновился?.Invoke(
                    сеанс);
            }
        }
