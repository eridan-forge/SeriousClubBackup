namespace серьёзный.Core.CoreThemes;

// Тема — папка с логотипом (logo.png) и фоном.
// Фон это либо СПИСОК видео (bg.mp4, bg2.mp4, bg3.mp4 ... — играют
// по очереди и зацикливаются), либо одна картинка bg.png/jpg/jpeg.
// Файлы, имя которых начинается на "fg", игнорируются (старый эффект пепла).
public class ТемаВхода
{
    public string Id { get; set; } = "";

    // Плейлист видео темы, уже отсортированный по имени.
    public List<string> Видео { get; set; } = new();

    public string ПутьФонИзображение { get; set; } = "";

    // Совместимость со старым кодом: первое видео плейлиста.
    public string ПутьФонВидео =>
        Видео.Count > 0 ? Видео[0] : "";

    public bool ФонЭтоВидео =>
        Видео.Count > 0;

    public string ПутьЛого { get; set; } = "";
}