namespace серьёзный.Core.CoreWeather;

// Расшифровка WMO-кодов. Живёт в Core, чтобы и сервер, и экран клуба
// пользовались ОДНОЙ таблицей — иконки меняются в одном месте.
public static class ПогодаКоды
{
    public static (string Описание, string Иконка) Расшифровать(int код, bool день)
    {
        return код switch
        {
            0 => ("Ясно", день ? "☀️" : "🌙"),
            1 => ("Малооблачно", день ? "🌤" : "🌙"),
            2 => ("Облачно", "⛅"),
            3 => ("Пасмурно", "☁️"),
            45 or 48 => ("Туман", "🌫"),
            51 or 53 or 55 => ("Морось", "🌦"),
            56 or 57 => ("Гололёд", "🌧"),
            61 or 63 or 65 => ("Дождь", "🌧"),
            66 or 67 => ("Ледяной дождь", "🌧"),
            71 or 73 or 75 => ("Снег", "🌨"),
            77 => ("Снежная крупа", "❄️"),
            80 or 81 or 82 => ("Ливень", "🌦"),
            85 or 86 => ("Снегопад", "🌨"),
            95 => ("Гроза", "⛈"),
            96 or 99 => ("Гроза с градом", "⛈"),
            _ => ("—", "❔")
        };
    }
}