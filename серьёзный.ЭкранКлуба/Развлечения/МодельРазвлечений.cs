public enum РедкостьПредмета
{
    Обычный,
    Синий,
    Фиолетовый,
    Красный,
    Золотой
}

public static class РедкостьСтиль
{
    public static Color Цвет(РедкостьПредмета редкость) => редкость switch
    {
        РедкостьПредмета.Синий => Color.FromRgb(0x3B, 0x82, 0xF6),
        РедкостьПредмета.Фиолетовый => Color.FromRgb(0xA8, 0x55, 0xF7),
        РедкостьПредмета.Красный => Color.FromRgb(0xEF, 0x44, 0x44),
        РедкостьПредмета.Золотой => Color.FromRgb(0xFB, 0xBF, 0x24),
        _ => Color.FromRgb(0x8A, 0x8F, 0x9A)
    };

    public static int БазовыйВес(РедкостьПредмета редкость) => редкость switch
    {
        РедкостьПредмета.Обычный => 500,
        РедкостьПредмета.Синий => 250,
        РедкостьПредмета.Фиолетовый => 120,
        РедкостьПредмета.Красный => 45,
        РедкостьПредмета.Золотой => 8,
        _ => 1
    };
}

public class ПредметКейса
{
    public string Название { get; set; } = "";
    public string Иконка { get; set; } = "🎁";
    public РедкостьПредмета Редкость { get; set; } = РедкостьПредмета.Обычный;
    public string Значение { get; set; } = "";
    public int Вес => РедкостьСтиль.БазовыйВес(Редкость);
}

public class ОпределениеКейса
{
    public string Название { get; set; } = "";
    public string Иконка { get; set; } = "📦";
    public List<ПредметКейса> Предметы { get; set; } = new();

    public ПредметКейса ВыбратьСлучайный(Random random)
    {
        int суммаВесов = Предметы.Sum(x => x.Вес);
        int бросок = random.Next(0, суммаВесов);
        int накоплено = 0;

        foreach (var предмет in Предметы)
        {
            накоплено += предмет.Вес;
            if (бросок < накоплено)
                return предмет;
        }

        return Предметы[^1];
    }
}

