    // =====================================================
    // ГЕОМЕТРИЯ ДУГИ
    //
    // Раньше это были const — теперь обычные поля: компактные
    // карусели-превью (по одной на категорию на странице "Игры")
    // должны рисоваться заметно меньше основной, но по той же логике.
    // УстановитьМасштаб() пропорционально уменьшает и радиус дуги, и
    // сам размер карточек — вызывай его ДО Загрузить().
    // =====================================================

    private const double ШиринаКарточкиБаза = 360;
    private const double ВысотаКарточкиБаза = 480;

    private const double УголНаШаг = 30;            // увеличено — при больших карточках нужен больший шаг
    private double РадиусДугиБаза = 680;            // виртуальный радиус окружности карусели
    private double ГлубинаВыступаБаза = 130;        // насколько боковые карточки выступают к зрителю

    private double базовыйМасштаб = 1.0;

    private const double МинимальныйМасштаб = 0.6;
    private const double ШагУменьшенияМасштаба = 0.16;

    // Центр + 2 по бокам = 5 карточек одновременно в кадре.
    private int видимыйДиапазон = 2;

    // Компактные карусели-превью встраиваются в страницу, которая сама
    // прокручивается колесом вертикально — если они будут перехватывать
    // колесо под собой, прокрутить страницу мимо них станет невозможно.
    // Полноразмерная карусель колесо обрабатывает как обычно.
    private bool обрабатыватьКолесо = true;

    private readonly List<КарточкаИгрыКарусель> карточки = new();

    private int целевойИндекс;

    // "Поколение" анимации — см. пояснение в ПодкрутитьК.
    private int поколениеАнимации;

    // Задержка между шагами прокрутки колесом. Пока действует — новые
    // тики колеса игнорируются, вместо того чтобы запускать вторую
    // анимацию поверх ещё не завершившейся первой (именно это раньше
    // давало "слишком быстро крутится / лагает" при быстрой прокрутке).
    private static readonly TimeSpan ЗадержкаКолеса = TimeSpan.FromMilliseconds(420);

    private DateTime последнийШагКолеса = DateTime.MinValue;

    public event Action<Игра>? ИграЗапущена;
    public event Action<Игра>? ИзбранноеИзменилось;
    public event Action<Игра>? ИграСкрыта;

    public КарусельИгр()
    {
        InitializeComponent();
    }

    // Вызывать ДО Загрузить(), если нужна компактная карусель-превью
    // (например, секция категории на странице "Игры") вместо
    // полноразмерной. 1.0 = как сейчас, 0.6 = заметно компактнее.
    public void УстановитьМасштаб(double коэффициент)
    {
        if (коэффициент <= 0)
            коэффициент = 1;

        базовыйМасштаб = коэффициент;
    }

    public void УстановитьВидимыйДиапазон(int диапазон)
    {
        if (диапазон < 1)
            диапазон = 1;

        видимыйДиапазон = диапазон;
    }

    // Для карусели-превью внутри прокручиваемой страницы — см.
    // комментарий у обрабатыватьКолесо выше.
    public void ОтключитьПрокруткуКолесом()
    {
        обрабатыватьКолесо = false;
    }

    // =====================================================
    // МЕДИАТОР ДЛЯ ПЛАВНОЙ АНИМАЦИИ ЦЕНТРА
    // =====================================================

    public static readonly DependencyProperty ТекущийИндексProperty =
        DependencyProperty.Register(
            nameof(ТекущийИндекс),
            typeof(double),
            typeof(КарусельИгр),
            new PropertyMetadata(0.0, ОнТекущийИндексИзменился));

    public double ТекущийИндекс
    {
        get => (double)GetValue(ТекущийИндексProperty);
        set => SetValue(ТекущийИндексProperty, value);
    }

    private static void ОнТекущийИндексИзменился(
        DependencyObject d,
        DependencyPropertyChangedEventArgs e)
    {
        if (d is КарусельИгр карусель)
            карусель.ПерепозиционироватьВсе();
    }

    // =====================================================
    // ЗАГРУЗКА ДАННЫХ
    // =====================================================

    public void Загрузить(
        IReadOnlyList<Игра> игры,
        ISet<Guid> избранные)
    {
        Guid? центральнаяРаньше =
            карточки.Count > 0 && целевойИндекс >= 0 && целевойИндекс < карточки.Count
                ? карточки[целевойИндекс].Игра?.Id
                : null;

        Сцена.Children.Clear();
        карточки.Clear();

        ТекстПусто.Visibility = игры.Count == 0 ? Visibility.Visible : Visibility.Collapsed;

        КнопкаНазад.Visibility = игры.Count > 1 ? Visibility.Visible : Visibility.Collapsed;
        КнопкаВперёд.Visibility = игры.Count > 1 ? Visibility.Visible : Visibility.Collapsed;

        for (int i = 0; i < игры.Count; i++)
        {
            var игра = игры[i];
            var индексКарточки = i;

            var карточка = new КарточкаИгрыКарусель();

            карточка.Загрузить(игра, избранные.Contains(игра.Id));

            карточка.ИграЗапущена += игра2 => ИграЗапущена?.Invoke(игра2);
            карточка.ИзбранноеИзменилось += игра2 => ИзбранноеИзменилось?.Invoke(игра2);
            карточка.ИграСкрыта += игра2 => ИграСкрыта?.Invoke(игра2);

            карточка.PreviewMouseLeftButtonDown += (_, ev) =>
            {
                if (индексКарточки != целевойИндекс)
                {
                    ПодкрутитьК(индексКарточки);
                    ev.Handled = true;
                    return;
                }

                // Уже по центру — клик по обложке/названию (не по одной
                                // из кнопок карточки) открывает превью игры.
                               if (карточка.Игра != null &&
                НайтиПредкаТипа<Button>(ev.OriginalSource as DependencyObject) == null)
                                   {
                    ИграЗапущена?.Invoke(карточка.Игра);
                                    }
            };

            карточки.Add(карточка);
            Сцена.Children.Add(карточка);
        }

        int новыйЦентральныйИндекс = 0;

        if (центральнаяРаньше.HasValue)
        {
            var найденный = карточки.FindIndex(x => x.Игра?.Id == центральнаяРаньше.Value);

            if (найденный >= 0)
                новыйЦентральныйИндекс = найденный;
        }

        целевойИндекс = новыйЦентральныйИндекс;

        // Обрываем любую незавершённую анимацию и объявляем её
        // поколение неактуальным — иначе её Completed мог бы сработать
        // позже и откатить только что установленный индекс.
        поколениеАнимации++;
        BeginAnimation(ТекущийИндексProperty, null);
        ТекущийИндекс = новыйЦентральныйИндекс;


    }

    private static T? НайтиПредкаТипа<T>(DependencyObject? узел) where T : DependencyObject
    {
        while (узел != null)
        {
            if (узел is T найден)
                return найден;

            узел = VisualTreeHelper.GetParent(узел);
        }

        return null;
    }

    // =====================================================
    // НАВИГАЦИЯ
    // =====================================================

    private void КнопкаНазад_Click(object sender, RoutedEventArgs e) => ПодкрутитьК(целевойИндекс - 1);

    private void КнопкаВперёд_Click(object sender, RoutedEventArgs e) => ПодкрутитьК(целевойИндекс + 1);

    private void Карусель_MouseWheel(object sender, MouseWheelEventArgs e)
    {
        if (!обрабатыватьКолесо)
            return; // e.Handled нарочно не трогаем — колесо уйдёт странице выше

        e.Handled = true;

        if (DateTime.Now - последнийШагКолеса < ЗадержкаКолеса)
            return;

        последнийШагКолеса = DateTime.Now;

        ПодкрутитьК(целевойИндекс + (e.Delta < 0 ? 1 : -1));
    }

    protected override void OnPreviewKeyDown(KeyEventArgs e)
    {
        if (e.Key == Key.Left)
        {
            ПодкрутитьК(целевойИндекс - 1);
            e.Handled = true;
        }
        else if (e.Key == Key.Right)
        {
            ПодкрутитьК(целевойИндекс + 1);
            e.Handled = true;
        }

        base.OnPreviewKeyDown(e);
    }

    // Крутит карусель к physическому индексу карточки (0..N-1),
    // выбирая кратчайший путь по кольцу.
    private void ПодкрутитьК(int индекс)
    {
        if (карточки.Count == 0)
            return;

        int количество = карточки.Count;

        double лучший = индекс;
        double лучшаяРазница = Math.Abs(индекс - ТекущийИндекс);

        foreach (var вариант in new[] { индекс - количество, индекс + количество })
        {
            var разница = Math.Abs(вариант - ТекущийИндекс);

            if (разница < лучшаяРазница)
            {
                лучшаяРазница = разница;
                лучший = вариант;
            }
        }

        целевойИндекс = ((индекс % количество) + количество) % количество;

        // РАНЬШЕ: у Completed каждой анимации был один и тот же паттерн
        // "снять анимацию и выставить нормализованное значение". При
        // быстрой прокрутке колесом новая анимация запускалась ПОВЕРХ
        // ещё не завершившейся старой — BeginAnimation на том же
        // свойстве заменяет старую, и её Completed срабатывает почти
        // сразу после замены. Тот СТАРЫЙ Completed видел уже ЧУЖОЕ
        // (новое) значение ТекущийИндекс, гасил анимацию через
        // BeginAnimation(prop, null) — убивая и новую, ещё даже не
        // начавшую двигаться, — и выставлял индекс, посчитанный от
        // чужого промежуточного значения. Это и выглядело как "крутишь
        // колесо — она случайно останавливается не там, карточки
        // пропадают".
        //
        // Фикс: у каждого вызова ПодкрутитьК — свой номер поколения.
        // Completed срабатывает только если это поколение всё ещё
        // актуально (после него никто не запускал новую анимацию).
        var моёПоколение = ++поколениеАнимации;

        var анимация = new DoubleAnimation(
            ТекущийИндекс,
            лучший,
            TimeSpan.FromMilliseconds(460))
        {
            EasingFunction = new CubicEase { EasingMode = EasingMode.EaseOut }
        };

        анимация.Completed += (_, _) =>
        {
            if (моёПоколение != поколениеАнимации)
                return;

            var нормализованное = ((ТекущийИндекс % количество) + количество) % количество;

            BeginAnimation(ТекущийИндексProperty, null);
            ТекущийИндекс = нормализованное;
        };

        BeginAnimation(ТекущийИндексProperty, анимация);
    }

