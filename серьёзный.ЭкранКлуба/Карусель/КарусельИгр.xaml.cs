using System;
using System.Collections.Generic;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Input;
using System.Windows.Media.Animation;
using серьёзный.Модели;

namespace серьёзный.ЭкранКлуба.Карусель;

public partial class КарусельИгр : UserControl
{
    // =====================================================
    // ГЕОМЕТРИЯ ДУГИ — можно спокойно подстраивать под вкус
    // =====================================================

    private const double ШиринаКарточки = 360;   // должно совпадать с
    private const double ВысотаКарточки = 480;   // Width/Height в КарточкаИгрыКарусель.xaml

    private const double УголНаШаг = 24;          // градусов между соседними карточками
    private const double РадиусДуги = 620;        // виртуальный радиус окружности карусели
    private const double ГлубинаОткатаНазад = 170;// насколько дальние карточки "уходят вглубь"
    private const double МинимальныйМасштаб = 0.6;
    private const double ШагУменьшенияМасштаба = 0.16;
    private const int ВидимыйДиапазон = 3;        // сколько карточек видно в каждую сторону от центра

    private readonly List<КарточкаИгрыКарусель> карточки = new();

    private int целевойИндекс;

    public event Action<Игра>? ИграЗапущена;
    public event Action<Игра>? ИзбранноеИзменилось;
    public event Action<Игра>? ИграСкрыта;

    public КарусельИгр()
    {
        InitializeComponent();
    }

    // =====================================================
    // МЕДИАТОР ДЛЯ ПЛАВНОЙ АНИМАЦИИ ЦЕНТРА
    //
    // Canvas.Left/PlaneProjection/ScaleTransform не умеют сами плыть от
    // "текущего дробного индекса" к целевому - это обычное animatable
    // double-свойство, при изменении которого на каждом кадре
    // пересчитываются позиции всех карточек. Тот же приём уже есть в
    // проекте - см. серьёзный/CrystalUI/Behaviors/SmoothScrollBehavior.cs
    // =====================================================

    public static readonly DependencyProperty ТекущийИндексProperty =
        DependencyProperty.Register(
            nameof(ТекущийИндекс),
            typeof(double),
            typeof(КарусельИгр),
            new PropertyMetadata(0.0, ОнТекущийИндексИзменился));

    public double ТекущийИндекс
    {
        get => (double)GetValue(ТекущийИндексProperty);
        set => SetValue(ТекущийИндексProperty, value);
    }

    private static void ОнТекущийИндексИзменился(
        DependencyObject d,
        DependencyPropertyChangedEventArgs e)
    {
        if (d is КарусельИгр карусель)
            карусель.ПерепозиционироватьВсе();
    }

    // =====================================================
    // ЗАГРУЗКА ДАННЫХ
    // =====================================================

    public void Загрузить(
        IReadOnlyList<Игра> игры,
        ISet<Guid> избранные)
    {
        // Запоминаем, какая игра была в центре, чтобы после
        // периодического обновления списка (раз в 15 сек, см.
        // ОкноИгрока) карусель не прыгала обратно к первой игре
        // прямо во время просмотра игроком.
        Guid? центральнаяРаньше =
            карточки.Count > 0 && целевойИндекс >= 0 && целевойИндекс < карточки.Count
                ? карточки[целевойИндекс].Игра?.Id
                : null;

        Сцена.Children.Clear();
        карточки.Clear();

        ТекстПусто.Visibility = игры.Count == 0 ? Visibility.Visible : Visibility.Collapsed;

        КнопкаНазад.Visibility = игры.Count > 1 ? Visibility.Visible : Visibility.Collapsed;
        КнопкаВперёд.Visibility = игры.Count > 1 ? Visibility.Visible : Visibility.Collapsed;

        for (int i = 0; i < игры.Count; i++)
        {
            var игра = игры[i];
            var индексКарточки = i;

            var карточка = new КарточкаИгрыКарусель();

            карточка.Загрузить(игра, избранные.Contains(игра.Id));

            // Форвардинг событий наружу - через лямбды, а не через
            // "+= ИграЗапущена" напрямую: событие this-класса в момент
            // создания карточки может быть ещё null (никто не
            // подписался), а += на голое имя события захватило бы
            // именно ТЕКУЩЕЕ (возможно null) значение, а не "то, что
            // подписано сейчас" на каждый вызов.
            карточка.ИграЗапущена += игра2 => ИграЗапущена?.Invoke(игра2);
            карточка.ИзбранноеИзменилось += игра2 => ИзбранноеИзменилось?.Invoke(игра2);
            карточка.ИграСкрыта += игра2 => ИграСкрыта?.Invoke(игра2);

            // Клик по НЕ центральной карточке - подкрутить её к центру
            // вместо мгновенного попадания по её кнопкам.
            // PreviewMouseLeftButtonDown - туннельное событие, доходит
            // до карточки РАНЬШЕ её собственных кнопок, поэтому
            // e.Handled=true здесь надёжно "съедает" клик, если
            // карточка ещё не в фокусе (когда она уже в фокусе - ничего
            // не делаем, и клик доходит до Играть/★/скрыть как обычно).
            карточка.PreviewMouseLeftButtonDown += (_, ev) =>
            {
                if (индексКарточки != целевойИндекс)
                {
                    ПодкрутитьК(индексКарточки);
                    ev.Handled = true;
                }
            };

            карточки.Add(карточка);
            Сцена.Children.Add(карточка);
        }

        int новыйЦентральныйИндекс = 0;

        if (центральнаяРаньше.HasValue)
        {
            var найденный = карточки.FindIndex(x => x.Игра?.Id == центральнаяРаньше.Value);

            if (найденный >= 0)
                новыйЦентральныйИндекс = найденный;
        }

        // Без анимации - это фоновое обновление списка, а не действие
        // игрока, скачок с плавной анимацией тут выглядел бы как дёрганье.
        целевойИндекс = новыйЦентральныйИндекс;

        BeginAnimation(ТекущийИндексProperty, null);
        ТекущийИндекс = новыйЦентральныйИндекс;
    }

    // =====================================================
    // НАВИГАЦИЯ
    // =====================================================

    private void КнопкаНазад_Click(object sender, RoutedEventArgs e) => ПодкрутитьК(целевойИндекс - 1);

    private void КнопкаВперёд_Click(object sender, RoutedEventArgs e) => ПодкрутитьК(целевойИндекс + 1);

    private void Карусель_MouseWheel(object sender, MouseWheelEventArgs e)
    {
        e.Handled = true;

        ПодкрутитьК(целевойИндекс + (e.Delta < 0 ? 1 : -1));
    }

    protected override void OnPreviewKeyDown(KeyEventArgs e)
    {
        if (e.Key == Key.Left)
        {
            ПодкрутитьК(целевойИндекс - 1);
            e.Handled = true;
        }
        else if (e.Key == Key.Right)
        {
            ПодкрутитьК(целевойИндекс + 1);
            e.Handled = true;
        }

        base.OnPreviewKeyDown(e);
    }

    // Крутит карусель к physическому индексу карточки (0..N-1),
    // выбирая КРАТЧАЙШИЙ путь по кольцу - например с последней
    // карточки "Вперёд" едет не через весь список назад, а продолжая
    // движение вперёд (и наоборот) - карусель зациклена по-настоящему,
    // а не просто изогнута визуально.
    private void ПодкрутитьК(int индекс)
    {
        if (карточки.Count == 0)
            return;

        int количество = карточки.Count;

        double лучший = индекс;
        double лучшаяРазница = Math.Abs(индекс - ТекущийИндекс);

        foreach (var вариант in new[] { индекс - количество, индекс + количество })
        {
            var разница = Math.Abs(вариант - ТекущийИндекс);

            if (разница < лучшаяРазница)
            {
                лучшаяРазница = разница;
                лучший = вариант;
            }
        }

        целевойИндекс = ((индекс % количество) + количество) % количество;

        var анимация = new DoubleAnimation(
            ТекущийИндекс,
            лучший,
            TimeSpan.FromMilliseconds(460))
        {
            EasingFunction = new CubicEase { EasingMode = EasingMode.EaseOut }
        };

        анимация.Completed += (_, _) =>
        {
            // Перебазируем накопленное значение обратно в 0..N-1 -
            // сама картинка от этого не меняется (смещения и так
            // считаются с учётом кольца), это только гигиена чисел,
            // чтобы за долгую смену в клубе индекс не улетал в
            // бесконечность.
            var нормализованное = ((ТекущийИндекс % количество) + количество) % количество;

            BeginAnimation(ТекущийИндексProperty, null);
            ТекущийИндекс = нормализованное;
        };

        BeginAnimation(ТекущийИндексProperty, анимация);
    }

    // =====================================================
    // РАСКЛАДКА ПО ДУГЕ
    // =====================================================

    private void Сцена_SizeChanged(object sender, SizeChangedEventArgs e) => ПерепозиционироватьВсе();

    private void ПерепозиционироватьВсе()
    {
        if (карточки.Count == 0)
            return;

        double центрX = Сцена.ActualWidth / 2;
        double центрY = Сцена.ActualHeight / 2;

        int количество = карточки.Count;

        for (int i = 0; i < количество; i++)
        {
            double смещение = СмещениеСУчётомКольца(i, ТекущийИндекс, количество);

            var карточка = карточки[i];

            if (Math.Abs(смещение) > ВидимыйДиапазон + 1.2)
            {
                карточка.Visibility = Visibility.Collapsed;
                continue;
            }

            карточка.Visibility = Visibility.Visible;

            double уголРад = смещение * (УголНаШаг * Math.PI / 180.0);

            double x = Math.Sin(уголРад) * РадиусДуги;
            double уходВглубь = (1 - Math.Cos(Math.Abs(уголРад))) * ГлубинаОткатаНазад;

            double абсСмещение = Math.Abs(смещение);

            double масштаб = Math.Max(МинимальныйМасштаб, 1.0 - абсСмещение * ШагУменьшенияМасштаба);

            double поворотY = Math.Clamp(смещение * УголНаШаг * 1.3, -62, 62);

            Canvas.SetLeft(карточка, центрX + x - (ШиринаКарточки * масштаб / 2));
            Canvas.SetTop(карточка, центрY - уходВглубь * 0.35 - (ВысотаКарточки * масштаб / 2));

            карточка.МасштабКарточки = масштаб;
            карточка.УголПоворота = поворотY;

            // Без PlaneProjection карточка не "разворачивается" по-настоящему -
                        // лёгкое затухание прозрачности к краям дуги достраивает иллюзию
                        // глубины взамен утраченного 3D-поворота.
            карточка.Opacity = Math.Max(0.35, 1.0 - абсСмещение * 0.22);

            Panel.SetZIndex(карточка, 1000 - (int)Math.Round(абсСмещение * 10));
        }
    }

    // Смещение карточки с индексом "индекс" относительно текущего
    // (возможно дробного) центра - выбираем кратчайший путь из
    // вариантов "как есть", "минус целый круг", "плюс целый круг".
    private static double СмещениеСУчётомКольца(int индекс, double центр, int количество)
    {
        double смещение = индекс - центр;

        if (количество <= 1)
            return смещение;

        foreach (var вариант in new[] { смещение - количество, смещение + количество })
        {
            if (Math.Abs(вариант) < Math.Abs(смещение))
                смещение = вариант;
        }

        return смещение;
    }
}