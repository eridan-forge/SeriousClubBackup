using System;

namespace серьёзный.ЭкранКлуба.Сервисы;

// Единственный захардкоженный тестовый аккаунт. Вводится на экране входа
// как обычный телефон + пароль, но Войти_Click узнаёт именно эти значения
// и открывает ОкноИгрока напрямую — без AccountLoginBridgeService, без
// Патруля, без сервера. Внутри ОкноИгрока.ЗапроситьАккаунтЧерезСерверAsync
// узнаёт Id и возвращает данные ниже мгновенно, вместо похода в
// AccountBalanceBridgeService.
//
// Меняй Телефон/Пароль/НачальныйОстаток здесь же, если нужны другие
// тестовые значения — больше нигде их указывать не нужно.
public static class ТестовыйАккаунт
{
    // Собственный Guid, который не пересечётся ни с одним настоящим
    // Guid.NewGuid() аккаунта.
    public static readonly Guid Id =
        Guid.Parse("00000000-0000-0000-0000-000000000001");

    // Уже в нормализованном виде (11 цифр, начинается с 7) — именно
    // это возвращает НормализоватьДляВхода. На экране входа можно
    // ввести, например, "0000000000".
    public const string Телефон = "70000000000";

    public const string Пароль = "test";

    public const string Имя = "Тестовый аккаунт";

    public static readonly TimeSpan НачальныйОстаток =
        TimeSpan.FromHours(2);
}