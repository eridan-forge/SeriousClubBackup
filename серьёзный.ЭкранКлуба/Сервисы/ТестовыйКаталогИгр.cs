using System;
using System.Collections.Generic;
using System.Security.Cryptography;
using System.Text;
using серьёзный.Модели;


namespace серьёзный.ЭкранКлуба.Сервисы;

// Выдуманные карточки для тестового аккаунта (ТестовыйАккаунт) — чтобы
// на странице "Игры" было много категорий и карусель под каждой,
// без затрагивания реального каталога ПК (СервисИгр/PC{id}.json).
public static class ТестовыйКаталогИгр
{
    private static readonly string[] Категории =
    {
        "Шутеры", "MOBA", "RPG", "Стратегии", "Гонки",
        "Спорт", "Песочницы", "Хорроры", "Файтинги", "Инди"
    };

    public static List<Игра> Сгенерировать()
    {
        var список = new List<Игра>();
        int счётчик = 1;

        foreach (var категория in Категории)
        {
            for (int i = 1; i <= 8; i++)
            {
                список.Add(new Игра
                {
                    Id = СтабильныйId(категория, i),
                    Название = $"{категория} {i}",
                    Категория = категория,
                    Описание =
$"Тестовая игра №{счётчик} в категории «{категория}». " +
"Динамичный командный шутер с быстрым темпом раундов, системой " +
"покупки снаряжения между раундами и упором на тактику и меткость — " +
"здесь достаточно текста, чтобы увидеть быструю печать по буквам " +
"в новом окне подробностей об игре.",
                    Путь = "",
                    Обложка = "",
                    Порядок = счётчик,
                    Скрыта = false,
                    AppId = "",
                    Launcher = "Тест"
                });

                счётчик++;
            }
        }

        return список;
    }

    private static Guid СтабильныйId(string категория, int индекс)
    {
        using var md5 = MD5.Create();
        var хеш = md5.ComputeHash(Encoding.UTF8.GetBytes($"{категория}-{индекс}"));
        return new Guid(хеш);
    }
}