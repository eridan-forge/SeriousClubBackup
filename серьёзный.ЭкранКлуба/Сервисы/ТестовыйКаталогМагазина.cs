    private static Guid СтабильныйId(string соль, string значение)
    {
        using var md5 = MD5.Create();
        var хеш = md5.ComputeHash(Encoding.UTF8.GetBytes($"{соль}-{значение}"));
        return new Guid(хеш);
    }
