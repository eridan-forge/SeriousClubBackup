    public static ShopCatalogDto Сгенерировать()
    {
        var категории = new List<ShopCategoryDto>();
        var товары = new List<ShopItemDto>();

        int порядок = 0;

        foreach (var (названиеРаздела, список) in Разделы)
        {
            var categoryId = СтабильныйId("category", названиеРаздела);

            категории.Add(new ShopCategoryDto
            {
                Id = categoryId,
                Name = названиеРаздела,
                Order = порядок++
            });

            for (int i = 0; i < список.Count; i++)
            {
                var заготовка = список[i];

                товары.Add(new ShopItemDto
                {
                    Id = СтабильныйId("item", названиеРаздела + заготовка.Название),
                    CategoryId = categoryId,
                    Name = заготовка.Название,
                    Description = заготовка.Описание,
                    Price = заготовка.Цена,
                    Image = "",
                    ImageData = null,
                    ImageExtension = null,
                    // Каждый третий товар — "хит", каждый пятый — "новинка":
                    // просто чтобы бейджи на карточке было на чём посмотреть.
                    Featured = i % 3 == 0,
                    IsNew = i % 5 == 0,
                    Stock = -1
                });
            }
        }

        return new ShopCatalogDto
        {
            Enabled = true,
            Categories = категории,
            Items = товары
        };
    }

