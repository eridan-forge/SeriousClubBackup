using System;
using серьёзный.Патруль.Модели;

namespace серьёзный.Патруль.Система
{
    public class СервисСостоянияПК
    {
        private readonly СостояниеПк состояние;

        public СервисСостоянияПК(
            СостояниеПк состояние)
        {
            this.состояние =
                состояние
                ?? throw new ArgumentNullException(
                    nameof(состояние));
        }

        // =========================================================
        // ПОЛУЧИТЬ ТЕКУЩЕЕ СОСТОЯНИЕ
        // =========================================================

        public СостояниеПк Получить()
        {
            состояние.Время =
                DateTime.Now;

            return состояние;
        }


        // =========================================================
        // КОМПЬЮТЕР
        // =========================================================

        public int КомпьютерId =>
            состояние.КомпьютерId;

        public string ИмяWindows =>
            состояние.ИмяWindows;

        public string IPАдрес =>
            состояние.IPАдрес;

        public string MACАдрес =>
            состояние.MACАдрес;


        // =========================================================
        // СЕАНС
        // =========================================================

        public int? ПолучитьСеансId() =>
            состояние.СеансId;

        public bool СеансАктивен =>
            состояние.СеансАктивен;

        public void УстановитьСеанс(
            int? сеансId)
        {
            if (сеансId.HasValue &&
                сеансId.Value <= 0)
            {
                throw new ArgumentOutOfRangeException(
                    nameof(сеансId),
                    "Идентификатор сеанса должен быть больше нуля.");
            }

            состояние.СеансId =
                сеансId;

            состояние.СеансАктивен =
                сеансId.HasValue;

            состояние.Время =
                DateTime.Now;
        }

        public void ЗавершитьСеанс()
        {
            состояние.СеансId =
                null;

            состояние.СеансАктивен =
                false;

            состояние.Время =
                DateTime.Now;
        }


        // =========================================================
        // АККАУНТ
        // =========================================================

        public Guid? ПолучитьАккаунтId() =>
            состояние.АккаунтId;

        public bool АккаунтАктивен =>
            состояние.АккаунтId.HasValue;

        public void УстановитьАккаунт(
            Guid? аккаунтId)
        {
            состояние.АккаунтId =
                аккаунтId;

            if (!аккаунтId.HasValue)
            {
                состояние.ИмяАккаунта =
                    string.Empty;
            }

            состояние.Время =
                DateTime.Now;
        }

        public void ОчиститьАккаунт()
        {
            состояние.АккаунтId =
                null;

            состояние.ИмяАккаунта =
                string.Empty;

            состояние.Время =
                DateTime.Now;
        }


        // =========================================================
        // ИМЯ АККАУНТА
        // =========================================================

        public string ИмяАккаунта =>
            состояние.ИмяАккаунта ??
            string.Empty;

        public void УстановитьИмяАккаунта(
            string? имя)
        {
            состояние.ИмяАккаунта =
                имя?.Trim() ??
                string.Empty;

            состояние.Время =
                DateTime.Now;
        }


        // =========================================================
        // АКТИВНЫЙ ПОЛЬЗОВАТЕЛЬ
        // =========================================================

        public void УстановитьАктивногоПользователя(
            Guid аккаунтId,
            string имяАккаунта)
        {
            if (аккаунтId ==
                Guid.Empty)
            {
                throw new ArgumentException(
                    "Идентификатор аккаунта не может быть пустым.",
                    nameof(аккаунтId));
            }

            состояние.АккаунтId =
                аккаунтId;

            состояние.ИмяАккаунта =
                имяАккаунта?.Trim() ??
                string.Empty;

            состояние.Время =
                DateTime.Now;
        }

        public void ОчиститьАктивногоПользователя()
        {
            состояние.АккаунтId =
                null;

            состояние.ИмяАккаунта =
                string.Empty;

            состояние.Время =
                DateTime.Now;
        }


        // =========================================================
        // БЛОКИРОВКА
        // =========================================================

        public bool ПользовательЗаблокирован =>
            состояние.ПользовательЗаблокирован;

        public void УстановитьБлокировку(
            bool заблокирован)
        {
            состояние.ПользовательЗаблокирован =
                заблокирован;

            состояние.Время =
                DateTime.Now;
        }

        public void Заблокировать()
        {
            состояние.ПользовательЗаблокирован =
                true;

            состояние.Время =
                DateTime.Now;
        }

        public void Разблокировать()
        {
            состояние.ПользовательЗаблокирован =
                false;

            состояние.Время =
                DateTime.Now;
        }


        // =========================================================
        // ПОЛНОЕ СОСТОЯНИЕ СЕАНСА + АККАУНТА
        // =========================================================

        public void УстановитьСостояниеСеанса(
            int? сеансId,
            Guid? аккаунтId,
            string? имяАккаунта,
            bool заблокирован)
        {
            if (сеансId.HasValue &&
                сеансId.Value <= 0)
            {
                throw new ArgumentOutOfRangeException(
                    nameof(сеансId),
                    "Идентификатор сеанса должен быть больше нуля.");
            }

            if (аккаунтId.HasValue &&
                аккаунтId.Value == Guid.Empty)
            {
                throw new ArgumentException(
                    "Идентификатор аккаунта не может быть пустым.",
                    nameof(аккаунтId));
            }

            состояние.СеансId =
                сеансId;

            состояние.СеансАктивен =
                сеансId.HasValue;

            состояние.АккаунтId =
                аккаунтId;

            состояние.ИмяАккаунта =
                аккаунтId.HasValue
                    ? имяАккаунта?.Trim() ??
                      string.Empty
                    : string.Empty;

            состояние.ПользовательЗаблокирован =
                заблокирован;

            состояние.Время =
                DateTime.Now;
        }


        // =========================================================
        // ПОЛНЫЙ СБРОС ПОЛЬЗОВАТЕЛЯ
        // =========================================================

        public void СброситьСостояниеПользователя()
        {
            состояние.СеансId =
                null;

            состояние.СеансАктивен =
                false;

            состояние.АккаунтId =
                null;

            состояние.ИмяАккаунта =
                string.Empty;

            состояние.ПользовательЗаблокирован =
                true;

            состояние.Время =
                DateTime.Now;
        }


        // =========================================================
        // ПОЛНАЯ АКТИВАЦИЯ АККАУНТА + СЕАНСА
        // =========================================================
        //
        // Используется, когда сервер одновременно сообщает:
        // какой сеанс запущен и какой аккаунт должен быть открыт.
        //

        public void АктивироватьСеанс(
            int сеансId,
            Guid аккаунтId,
            string имяАккаунта)
        {
            if (сеансId <= 0)
            {
                throw new ArgumentOutOfRangeException(
                    nameof(сеансId),
                    "Идентификатор сеанса должен быть больше нуля.");
            }

            if (аккаунтId ==
                Guid.Empty)
            {
                throw new ArgumentException(
                    "Идентификатор аккаунта не может быть пустым.",
                    nameof(аккаунтId));
            }

            состояние.СеансId =
                сеансId;

            состояние.СеансАктивен =
                true;

            состояние.АккаунтId =
                аккаунтId;

            состояние.ИмяАккаунта =
                имяАккаунта?.Trim() ??
                string.Empty;

            состояние.ПользовательЗаблокирован =
                false;

            состояние.Время =
                DateTime.Now;
        }


        // =========================================================
        // ПОЛНОЕ ЗАВЕРШЕНИЕ СЕАНСА
        // =========================================================
        //
        // После завершения:
        // - сеанс очищается;
        // - аккаунт очищается;
        // - ПК снова блокируется.
        //

        public void ЗавершитьАктивныйСеанс()
        {
            состояние.СеансId =
                null;

            состояние.СеансАктивен =
                false;

            состояние.АккаунтId =
                null;

            состояние.ИмяАккаунта =
                string.Empty;

            состояние.ПользовательЗаблокирован =
                true;

            состояние.Время =
                DateTime.Now;
        }


        // =========================================================
        // ВЫХОД ИЗ АККАУНТА БЕЗ ЗАВЕРШЕНИЯ СЕАНСА
        // =========================================================
        //
        // Используется отдельно от завершения сеанса.
        //

        public void ВыйтиИзАккаунта()
        {
            состояние.АккаунтId =
                null;

            состояние.ИмяАккаунта =
                string.Empty;

            состояние.Время =
                DateTime.Now;
        }
    }
}