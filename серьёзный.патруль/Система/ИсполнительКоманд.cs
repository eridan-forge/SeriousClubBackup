using NAudio.Wave;
using System;
using System.Diagnostics;
using System.IO;
using System.Threading.Tasks;
using серьёзный.патруль.Сервисы;
using серьёзный.Патруль.Модели;
using серьёзный.Патруль.Окна;
using серьёзный.Патруль.Сервисы;
using серьёзный.Патруль.Сеть;
using серьёзный.Сеть;

namespace серьёзный.Патруль.Система
{
    public class ИсполнительКоманд
    {
        private readonly СервисСостоянияПК сервисСостояния;

        private readonly КлиентПатруля клиент;

        private readonly СервисБлокировки сервисБлокировки =
            new();


        public ИсполнительКоманд(
            СервисСостоянияПК сервисСостояния,
            КлиентПатруля клиент)
        {
            this.сервисСостояния =
                сервисСостояния
                ?? throw new ArgumentNullException(
                    nameof(сервисСостояния));

            this.клиент =
                клиент
                ?? throw new ArgumentNullException(
                    nameof(клиент));
        }


        // =========================================================
        // ОСНОВНОЙ ДИСПЕТЧЕР КОМАНД
        // =========================================================

        public async Task<РезультатКоманды> ВыполнитьAsync(
            СетевоеСообщение сообщение)
        {
            try
            {
                if (сообщение == null)
                {
                    return Ошибка(
                        "Сетевое сообщение отсутствует.");
                }

                var команда =
                    сообщение.ПолучитьДанные<
                        global::серьёзный.Сеть.КомандаПатрулю>();

                if (команда == null)
                {
                    return Ошибка(
                        "Команда отсутствует.");
                }

                switch (команда.Команда)
                {
                    // =================================================
                    // СОСТОЯНИЕ
                    // =================================================

                    case КомандаПК.ПолучитьСостояние:

                        return Успех();


                    // =================================================
                    // ПЕРЕЗАГРУЗКА
                    // =================================================

                    case КомандаПК.Перезагрузить:

                        await ПерезагрузитьAsync();

                        return Успех();


                    // =================================================
                    // ВЫКЛЮЧЕНИЕ
                    // =================================================

                    case КомандаПК.Выключить:

                        await ВыключитьAsync();

                        return Успех();


                    // =================================================
                    // УВЕДОМЛЕНИЕ
                    // =================================================

                    case КомандаПК.ПоказатьУведомление:

                        await ПоказатьУведомлениеAsync(
                            команда.Текст ??
                            string.Empty);

                        return Успех();


                    // =================================================
                    // ЧАТ
                    // =================================================

                    case КомандаПК.СообщениеЧата:

                        await ПоказатьЧатAsync(
                            команда.ИмяОтправителя ??
                            "Администратор",
                            команда.Текст ??
                            string.Empty);

                        return Успех();


                    // =================================================
                    // 15 МИНУТ
                    // =================================================

                    case КомандаПК.Предупреждение15Минут:

                        await ПоказатьУведомлениеAsync(
                            команда.Текст ??
                            "⚠ До окончания сеанса осталось 15 минут.");

                        return Успех();


                    // =================================================
                    // 10 МИНУТ
                    // =================================================

                    case КомандаПК.Предупреждение10Минут:

                        await ПоказатьУведомлениеAsync(
                            команда.Текст ??
                            "⚠ До окончания сеанса осталось 10 минут.");

                        return Успех();


                    // =================================================
                    // 5 МИНУТ
                    // =================================================

                    case КомандаПК.Предупреждение5Минут:

                        await ПоказатьУведомлениеAsync(
                            команда.Текст ??
                            "⚠ До окончания сеанса осталось 5 минут.");

                        return Успех();


                    // =================================================
                    // НАЧАТЬ СЕАНС
                    // =================================================

                    case КомандаПК.НачатьСеанс:

                        return НачатьСеанс(
                            команда.СеансId,
                            команда.ДлительностьСекунд,
                            команда.АккаунтId,
                            команда.ИмяАккаунта);


                    // =================================================
                    // ЗАВЕРШИТЬ СЕАНС
                    // =================================================

                    case КомандаПК.ЗавершитьСеанс:

                        await ЗавершитьСеансAsync(
                            команда.СеансId);

                        return Успех();


                    // =================================================
                    // ГОЛОСОВОЕ
                    // =================================================

                    case КомандаПК.ВоспроизвестиГолосовое:

                        if (string.IsNullOrWhiteSpace(
                                команда.АудиоBase64))
                        {
                            return Ошибка(
                                "Аудиозапись отсутствует.");
                        }

                        await ВоспроизвестиГолосовоеAsync(
                            команда.АудиоBase64);

                        return Успех();


                    // =================================================
                    // БЛОКИРОВКА
                    // =================================================

                    case КомандаПК.Заблокировать:

                        await ЗаблокироватьAsync();

                        return Успех();


                    // =================================================
                    // РАЗБЛОКИРОВКА
                    // =================================================

                    case КомандаПК.Разблокировать:

                        await РазблокироватьAsync();

                        return Успех();


                    // =================================================
                    // ПАРОЛЬ ЭКРАНА
                    // =================================================

                    case КомандаПК.СменитьПарольЭкрана:

                        СервисЭкрана.СменитьПароль(
                            команда.Текст ??
                            "123456");

                        return Успех();


                    // =================================================
                    // ТЕКСТ ЭКРАНА
                    // =================================================

                    case КомандаПК.ИзменитьЗаголовокЭкрана:

                        СервисЭкрана.ИзменитьТекст(
                            команда.Текст ??
                            string.Empty);

                        return Успех();


                    // =================================================
                    // УСТАНОВИТЬ АККАУНТ
                    // =================================================

                    case КомандаПК.УстановитьАккаунт:

                        return УстановитьАккаунт(
                            команда.АккаунтId,
                            команда.ИмяАккаунта);


                    // =================================================
                    // ОЧИСТИТЬ АККАУНТ
                    // =================================================

                    case КомандаПК.ОчиститьАккаунт:

                        ОчиститьАккаунт();

                        return Успех();


                    // =================================================
                    // ВЫЙТИ ИЗ АККАУНТА
                    // =================================================

                    case КомандаПК.ВыйтиИзАккаунта:

                        ВыйтиИзАккаунта();

                        return Успех();


                    // =================================================
                    // ЗАПРОС ВХОДА В АККАУНТ
                    //
                    // Пока серверная авторизация здесь не реализуется.
                    // Патруль сообщает, что команда распознана.
                    // Реальную проверку имени/пароля сделаем
                    // на стороне сервера.
                    // =================================================

                    case КомандаПК.ЗапроситьВходВАккаунт:

                        return Ошибка(
                            "Авторизация аккаунта пока выполняется на сервере.");


                    // =================================================
                    // ОТВЕТ НА ВХОД
                    //
                    // Это не команда, которую сервер отправляет
                    // Патрулю в текущей версии.
                    // Если она попадёт сюда случайно, это ошибка.
                    // =================================================

                    case КомандаПК.ОтветНаВходВАккаунт:

                        return Ошибка(
                            "Ответ авторизации не является командой Патрулю.");


                    // =================================================
                    // НЕИЗВЕСТНАЯ КОМАНДА
                    // =================================================

                    default:

                        return Ошибка(
                            "Неизвестная команда.");
                }
            }
            catch (Exception ошибка)
            {
                try
                {
                    Лог.Записать(
                        "Ошибка выполнения команды: " +
                        ошибка);
                }
                catch
                {
                }

                return Ошибка(
                    ошибка.Message);
            }
        }


        // =========================================================
        // ГОЛОСОВОЕ
        // =========================================================

        private static async Task ВоспроизвестиГолосовоеAsync(
            string base64)
        {
            byte[] bytes;

            try
            {
                bytes =
                    Convert.FromBase64String(
                        base64);
            }
            catch
            {
                throw new InvalidOperationException(
                    "Не удалось прочитать аудиозапись.");
            }

            if (bytes.Length == 0)
            {
                throw new InvalidOperationException(
                    "Аудиозапись пустая.");
            }

            using var поток =
                new MemoryStream(
                    bytes);

            using var reader =
                new WaveFileReader(
                    поток);

            using var output =
                new WaveOut();

            var завершение =
                new TaskCompletionSource<bool>(
                    TaskCreationOptions
                        .RunContinuationsAsynchronously);

            Exception? ошибкаВоспроизведения = null;

            output.PlaybackStopped +=
                (_, args) =>
                {
                    ошибкаВоспроизведения =
                        args.Exception;

                    завершение.TrySetResult(
                        true);
                };

            output.Init(
                reader);

            output.Play();

            await завершение.Task;

            if (ошибкаВоспроизведения != null)
            {
                throw new InvalidOperationException(
                    "Ошибка воспроизведения голосового сообщения.",
                    ошибкаВоспроизведения);
            }
        }


        // =========================================================
        // БЛОКИРОВКА
        // =========================================================

        private Task ЗаблокироватьAsync()
        {
            сервисСостояния
                .Заблокировать();

            сервисБлокировки
                .Заблокировать(
                    Environment.MachineName);

            СервисЭкрана
                .Заблокировать();

            return Task.CompletedTask;
        }


        // =========================================================
        // РАЗБЛОКИРОВКА
        // =========================================================

        private Task РазблокироватьAsync()
        {
            сервисСостояния
                .Разблокировать();

            сервисБлокировки
                .Разблокировать();

            СервисЭкрана
                .Разблокировать();

            return Task.CompletedTask;
        }


        // =========================================================
        // ПЕРЕЗАГРУЗКА
        // =========================================================

        private Task ПерезагрузитьAsync()
        {
            Process.Start(
                new ProcessStartInfo
                {
                    FileName =
                        "shutdown.exe",

                    Arguments =
                        "/r /t 5 /f",

                    UseShellExecute =
                        false,

                    CreateNoWindow =
                        true
                });

            return Task.CompletedTask;
        }


        // =========================================================
        // ВЫКЛЮЧЕНИЕ
        // =========================================================

        private Task ВыключитьAsync()
        {
            Process.Start(
                new ProcessStartInfo
                {
                    FileName =
                        "shutdown.exe",

                    Arguments =
                        "/s /t 5 /f",

                    UseShellExecute =
                        false,

                    CreateNoWindow =
                        true
                });

            return Task.CompletedTask;
        }


        // =========================================================
        // УВЕДОМЛЕНИЕ
        // =========================================================

        private Task ПоказатьУведомлениеAsync(
            string текст)
        {
            try
            {
                System.Windows.Application
                    .Current
                    .Dispatcher
                    .Invoke(
                        () =>
                        {
                            var окно =
                                new серьёзный
                                    .Патруль
                                    .Окна
                                    .ВсплывающееСообщение(
                                        "Администратор",
                                        текст);

                            окно.ОтветОтправлен +=
                                ОтправитьОтветВЧатAsync;

                            окно.Show();
                        });
            }
            catch (Exception ошибка)
            {
                try
                {
                    Лог.Записать(
                        "Ошибка ПоказатьУведомлениеAsync: " +
                        ошибка);
                }
                catch
                {
                }
            }

            return Task.CompletedTask;
        }


        // =========================================================
        // ЧАТ
        // =========================================================

        private Task ПоказатьЧатAsync(
            string имя,
            string текст)
        {
            try
            {
                System.Windows.Application
                    .Current
                    .Dispatcher
                    .Invoke(
                        () =>
                        {
                            var окно =
                                new Окна
                                    .ВсплывающееСообщение(
                                        имя,
                                        текст);

                            окно.ОтветОтправлен +=
                                ОтправитьОтветAsync;

                            окно.Show();
                        });
            }
            catch (Exception ошибка)
            {
                try
                {
                    Лог.Записать(
                        "Ошибка ПоказатьЧатAsync: " +
                        ошибка);
                }
                catch
                {
                }
            }

            return Task.CompletedTask;
        }


        // =========================================================
        // ОТВЕТ НА СООБЩЕНИЕ
        // =========================================================

        private async Task ОтправитьОтветAsync(
            string ответ)
        {
            var состояние =
                сервисСостояния
                    .Получить();

            var сообщение =
                СетевоеСообщение.Создать(
                    global::серьёзный.Сеть
                        .ТипСообщения.Чат);

            сообщение.КомпьютерId =
                состояние.КомпьютерId;

            сообщение.УстановитьДанные(
                new global::серьёзный.Сеть
                    .СообщениеЧата
                {
                    КомпьютерId =
                        состояние.КомпьютерId,

                    Имя =
                        состояние.ИмяWindows,

                    Текст =
                        ответ,

                    ОтИгрока =
                        true
                });

            await клиент
                .ОтправитьAsync(
                    сообщение);
        }


        // =========================================================
        // НАЧАЛО СЕАНСА
        // =========================================================

        private РезультатКоманды НачатьСеанс(
            int? сеансId,
            int? длительностьСекунд,
            Guid? аккаунтId,
            string? имяАккаунта)
        {
            if (!сеансId.HasValue ||
                сеансId.Value <= 0)
            {
                return Ошибка(
                    "Для запуска сеанса необходим корректный идентификатор сеанса.");
            }

            if (длительностьСекунд.HasValue &&
                длительностьСекунд.Value < 0)
            {
                return Ошибка(
                    "Некорректная длительность сеанса.");
            }

            if (аккаунтId.HasValue &&
                аккаунтId.Value == Guid.Empty)
            {
                return Ошибка(
                    "Некорректный идентификатор аккаунта.");
            }

            if (аккаунтId.HasValue)
            {
                сервисСостояния
                    .УстановитьАктивногоПользователя(
                        аккаунтId.Value,
                        имяАккаунта ??
                        string.Empty);
            }
            else
            {
                сервисСостояния
                    .ОчиститьАктивногоПользователя();
            }

            сервисСостояния
                .УстановитьСеанс(
                    сеансId);

            сервисСостояния
                .Разблокировать();

            СервисЭкрана
                 .УстановитьАккаунт(
                аккаунтId);

            СервисЭкрана
                .Разблокировать();

            return Успех();
        }


        // =========================================================
        // УСТАНОВИТЬ АККАУНТ
        // =========================================================

        private РезультатКоманды УстановитьАккаунт(
            Guid? аккаунтId,
            string? имяАккаунта)
        {
            if (!аккаунтId.HasValue ||
                аккаунтId.Value == Guid.Empty)
            {
                return Ошибка(
                    "Не указан корректный идентификатор аккаунта.");
            }

            var имя =
                имяАккаунта?.Trim() ??
                string.Empty;

            if (string.IsNullOrWhiteSpace(имя))
            {
                return Ошибка(
                    "Не указано имя аккаунта.");
            }

            сервисСостояния
                .УстановитьАктивногоПользователя(
                    аккаунтId.Value,
                    имя);

            return Успех();
        }


        // =========================================================
        // ОЧИСТИТЬ АККАУНТ
        // =========================================================

        private void ОчиститьАккаунт()
        {
            сервисСостояния
                .ОчиститьАктивногоПользователя();
        }


        // =========================================================
        // ВЫХОД ИЗ АККАУНТА
        // =========================================================

        private void ВыйтиИзАккаунта()
        {
            сервисСостояния
                .ВыйтиИзАккаунта();
        }


        // =========================================================
        // ЗАВЕРШЕНИЕ СЕАНСА
        // =========================================================

        private Task ЗавершитьСеансAsync(
            int? сеансId)
        {
            var текущийСеанс =
                сервисСостояния
                    .ПолучитьСеансId();

            // Если пришёл конкретный идентификатор,
            // проверяем, что он действительно относится
            // к текущему состоянию ПК.
            if (сеансId.HasValue &&
                текущийСеанс.HasValue &&
                сеансId.Value != текущийСеанс.Value)
            {
                return Task.FromResult(
                    УспешноеЗавершение());
            }

            сервисСостояния
                .ЗавершитьАктивныйСеанс();

            СервисЭкрана
                .УстановитьАккаунт(
                null);

            СервисЭкрана
                .Заблокировать();

            return Task.CompletedTask;
        }

        private static РезультатКоманды УспешноеЗавершение()
        {
            return Успех();
        }


        // =========================================================
        // ОТВЕТ ИЗ POPUP
        // =========================================================

        private async Task ОтправитьОтветВЧатAsync(
            string текст)
        {
            var состояние =
                сервисСостояния
                    .Получить();

            var сообщение =
                СетевоеСообщение.Создать(
                    серьёзный.Сеть
                        .ТипСообщения.Чат);

            сообщение.КомпьютерId =
                состояние.КомпьютерId;

            сообщение.УстановитьДанные(
                new серьёзный.Сеть
                    .СообщениеЧата
                {
                    КомпьютерId =
                        состояние.КомпьютерId,

                    Имя =
                        состояние.ИмяWindows,

                    Текст =
                        текст,

                    ОтИгрока =
                        true
                });

            await клиент
                .ОтправитьAsync(
                    сообщение);
        }


        // =========================================================
        // РЕЗУЛЬТАТ
        // =========================================================

        private static РезультатКоманды Успех()
        {
            return new РезультатКоманды
            {
                Успешно =
                    true
            };
        }

        private static РезультатКоманды Ошибка(
            string сообщение)
        {
            return new РезультатКоманды
            {
                Успешно =
                    false,

                Ошибка =
                    сообщение
            };
        }
    }


    public class РезультатКоманды
    {
        public bool Успешно { get; set; }

        public string? Ошибка { get; set; }
    }
}