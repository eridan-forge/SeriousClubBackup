using System;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;
using серьёзный.Core.CoreChat;
using серьёзный.Патруль.Сеть;
using серьёзный.Патруль.Система;
using серьёзный.Сеть;

namespace серьёзный.Патруль.Сервисы;

public class СервисПатруля : IDisposable
{
    private readonly КлиентПатруля клиент;
    private readonly СервисСостоянияПК состояние;
    private readonly ИсполнительКоманд исполнитель;

    private bool остановлен;

    public СервисПатруля(
        КлиентПатруля клиент,
        СервисСостоянияПК состояние,
        ИсполнительКоманд исполнитель)
    {
        this.клиент = клиент;
        this.состояние = состояние;
        this.исполнитель = исполнитель;

        this.клиент.ПолученоСообщение += ОбработатьСообщениеAsync;
        this.клиент.СоединениеПотеряно += ОбработатьПотерюСоединения;
    }

    public Task ЗапуститьAsync(CancellationToken токен)
    {
        остановлен = false;
        return клиент.ЗапуститьAsync(токен);
    }

    public void Остановить()
    {
        if (остановлен)
            return;

        остановлен = true;

        клиент.ПолученоСообщение -= ОбработатьСообщениеAsync;
        клиент.СоединениеПотеряно -= ОбработатьПотерюСоединения;

        клиент.Закрыть();
    }

    private void ОбработатьПотерюСоединения()
    {
        try
        {
            if (!остановлен)
            {
                состояние.Получить();
            }
        }
        catch
        {
        }
    }

    private async Task ОбработатьСообщениеAsync(СетевоеСообщение сообщение)
    {
        if (остановлен || сообщение == null)
            return;

        try
        {
            switch (сообщение.Тип)
            {
                case серьёзный.Сеть.ТипСообщения.Команда:
                    {
                        var результат =
                            await исполнитель.ВыполнитьAsync(сообщение);

                        var ответ =
                            СетевоеСообщение.Создать(
                                серьёзный.Сеть.ТипСообщения.ОтветНаКоманду);

                        ответ.КомпьютерId =
                            сообщение.КомпьютерId;

                        ответ.ИдентификаторСообщения =
                            сообщение.ИдентификаторСообщения;

                        ответ.Успешно =
                            результат.Успешно;

                        ответ.Ошибка =
                            результат.Ошибка;

                        if (!string.IsNullOrWhiteSpace(результат.Данные))
                        {
                            ответ.Данные =
                                 результат.Данные;
                        }

                        await клиент.ОтправитьAsync(ответ);

                        break;
                    }

                case серьёзный.Сеть.ТипСообщения.Чат:
                    {
                        if (string.IsNullOrWhiteSpace(сообщение.Данные))
                            break;

                        var msg =
                            JsonSerializer.Deserialize<ChatMessage>(
                                сообщение.Данные);

                        if (msg != null)
                        {
                            ChatLiveEvents.Raise(msg);
                        }

                        break;
                    }
            }
        }
        catch (Exception ex)
        {
            try
            {
                var ответ =
                    СетевоеСообщение.Создать(
                        серьёзный.Сеть.ТипСообщения.ОтветНаКоманду);

                ответ.КомпьютерId =
                    сообщение.КомпьютерId;

                ответ.ИдентификаторСообщения =
                    сообщение.ИдентификаторСообщения;

                ответ.Успешно = false;
                ответ.Ошибка = ex.Message;

                await клиент.ОтправитьAsync(ответ);
            }
            catch
            {
            }
        }
    }

    public void Dispose()
    {
        Остановить();
    }
}