using System;
using System.Diagnostics;
using System.Threading;
using System.Threading.Tasks;
using System.Windows;
using Microsoft.Win32;
using серьёзный.Патруль.Модели;
using серьёзный.Патруль.Сервисы;
using серьёзный.Патруль.Сеть;
using серьёзный.Патруль.Система;

namespace серьёзный.Патруль
{
    public partial class App : Application
    {
        private CancellationTokenSource? токенИсточника;

        private СервисПатруля? сервисПатруля;

        private КонфигурацияПатруля? конфигурация;

        private bool завершение;


        // =========================================================
        // STARTUP
        // =========================================================

        protected override void OnStartup(
            StartupEventArgs e)
        {
            ShutdownMode =
                ShutdownMode.OnExplicitShutdown;

            base.OnStartup(e);

            AppDomain.CurrentDomain.UnhandledException +=
                ОбработатьНеобработанноеИсключение;

            TaskScheduler.UnobservedTaskException +=
                ОбработатьНеожиданноеИсключениеЗадачи;

            DispatcherUnhandledException +=
                (_, ошибка) =>
                {
                    ЗаписатьЛог(
                        "DispatcherUnhandledException: " +
                        ошибка.Exception);

                    ошибка.Handled = true;
                };

            ДобавитьВАвтозапуск();

            токенИсточника =
                new CancellationTokenSource();

            _ = ЗапуститьПатрульAsync(
                токенИсточника.Token);
        }


        // =========================================================
        // ГЛАВНЫЙ ЦИКЛ ЗАПУСКА
        // =========================================================

        private async Task ЗапуститьПатрульAsync(
            CancellationToken токен)
        {
            while (!токен.IsCancellationRequested &&
                   !завершение)
            {
                try
                {
                    var успешно =
                        await ПопытатьсяЗапуститьAsync(
                            токен);

                    if (успешно)
                    {
                        return;
                    }
                }
                catch (OperationCanceledException)
                {
                    return;
                }
                catch (Exception ошибка)
                {
                    ЗаписатьЛог(
                        "Ошибка запуска Патруля: " +
                        ошибка);
                }

                if (токен.IsCancellationRequested ||
                    завершение)
                {
                    return;
                }

                try
                {
                    await Task.Delay(
                        TimeSpan.FromSeconds(5),
                        токен);
                }
                catch (OperationCanceledException)
                {
                    return;
                }
            }
        }


        // =========================================================
        // ПОПЫТКА ЗАПУСКА
        // =========================================================

        private async Task<bool> ПопытатьсяЗапуститьAsync(
            CancellationToken токен)
        {
            var файловаяКонфигурация =
                КонфигурацияПатруляЗагрузчик
                    .Загрузить();


            // -----------------------------------------------------
            // ПОЛУЧЕНИЕ АДРЕСА СЕРВЕРА
            // -----------------------------------------------------

            var адрес =
                await ПолучитьАдресСервераAsync(
                    файловаяКонфигурация,
                    токен);

            if (!адрес.HasValue)
            {
                ЗаписатьЛог(
                    "Адрес сервера не найден.");

                return false;
            }


            // -----------------------------------------------------
            // КОНФИГУРАЦИЯ
            // -----------------------------------------------------

            конфигурация =
                new КонфигурацияПатруля
                {
                    КомпьютерId =
                        файловаяКонфигурация
                            .КомпьютерId,

                    ИмяКомпьютера =
                        string.IsNullOrWhiteSpace(
                            файловаяКонфигурация.Имя)
                            ? Environment.MachineName
                            : файловаяКонфигурация.Имя.Trim(),

                    СерверIP =
                        адрес.Value.Ip,

                    СерверПорт =
                        адрес.Value.Port,

                    ТаймаутПодключенияСекунд =
                        5,

                    ИнтервалHeartbeatСекунд =
                        5
                };


            // -----------------------------------------------------
            // СОСТОЯНИЕ ПК
            // -----------------------------------------------------

            var состояниеПк =
                new СостояниеПк
                {
                    КомпьютерId =
                        файловаяКонфигурация
                            .КомпьютерId,

                    ИмяWindows =
                        Environment.MachineName,

                    WindowsЗапущен =
                        true,

                    ПользовательЗаблокирован =
                        true,

                    СеансАктивен =
                        false,

                    СеансId =
                        null,

                    АккаунтId =
                        null,

                    ИмяАккаунта =
                        string.Empty,

                    Время =
                        DateTime.Now,

                    ВерсияПатруля =
                        "1.0.0"
                };


            var сервисСостояния =
                new СервисСостоянияПК(
                    состояниеПк);


            // -----------------------------------------------------
            // КЛИЕНТ
            // -----------------------------------------------------

            var клиент =
                new КлиентПатруля(
                    конфигурация);


            // -----------------------------------------------------
            // ИСПОЛНИТЕЛЬ
            // -----------------------------------------------------

            var исполнитель =
                new ИсполнительКоманд(
                    сервисСостояния,
                    клиент);


            // -----------------------------------------------------
            // СЕРВИС
            // -----------------------------------------------------

            сервисПатруля =
                new СервисПатруля(
                    клиент,
                    сервисСостояния,
                    исполнитель);


            ЗаписатьЛог(
                $"Патруль ПК-{конфигурация.КомпьютерId} " +
                $"подготовлен. Сервер: " +
                $"{конфигурация.СерверIP}:" +
                $"{конфигурация.СерверПорт}");


            // -----------------------------------------------------
            // ВАЖНО
            //
            // Здесь больше НЕТ второго цикла переподключения.
            // Его полностью выполняет КлиентПатруля.
            // -----------------------------------------------------

            try
            {
                await сервисПатруля
                    .ЗапуститьAsync(
                        токен);
            }
            finally
            {
                сервисПатруля
                    .Остановить();

                сервисПатруля = null;
            }

            return true;
        }


        // =========================================================
        // ПОЛУЧЕНИЕ АДРЕСА СЕРВЕРА
        // =========================================================

        private async Task<(
            string Ip,
            int Port)?> ПолучитьАдресСервераAsync(
            КонфигурацияПатрульJson файловаяКонфигурация,
            CancellationToken токен)
        {
            // -----------------------------------------------------
            // 1. patrol.json
            // -----------------------------------------------------

            if (!string.IsNullOrWhiteSpace(
                    файловаяКонфигурация.СерверIP) &&
                файловаяКонфигурация.СерверПорт.HasValue &&
                файловаяКонфигурация.СерверПорт.Value > 0)
            {
                var ip =
                    файловаяКонфигурация
                        .СерверIP
                        .Trim();

                var port =
                    файловаяКонфигурация
                        .СерверПорт
                        .Value;

                КэшАдресаСервера.Сохранить(
                    ip,
                    port);

                ЗаписатьЛог(
                    $"Сервер взят из patrol.json: " +
                    $"{ip}:{port}");

                return (
                    ip,
                    port);
            }


            // -----------------------------------------------------
            // 2. ОБНАРУЖЕНИЕ
            // -----------------------------------------------------

            try
            {
                var найден =
                    await СервисОбнаруженияСервера
                        .НайтиСерверAsync(
                            TimeSpan.FromSeconds(5),
                            токен);

                if (найден.HasValue &&
                    !string.IsNullOrWhiteSpace(
                        найден.Value.Ip) &&
                    найден.Value.Port > 0)
                {
                    КэшАдресаСервера.Сохранить(
                        найден.Value.Ip,
                        найден.Value.Port);

                    ЗаписатьЛог(
                        $"Сервер обнаружен: " +
                        $"{найден.Value.Ip}:" +
                        $"{найден.Value.Port}");

                    return (
                        найден.Value.Ip,
                        найден.Value.Port);
                }
            }
            catch (OperationCanceledException)
            {
                throw;
            }
            catch (Exception ошибка)
            {
                ЗаписатьЛог(
                    "Ошибка обнаружения сервера: " +
                    ошибка);
            }


            // -----------------------------------------------------
            // 3. КЭШ
            // -----------------------------------------------------

            try
            {
                var кэш =
                    КэшАдресаСервера
                        .Загрузить();

                if (кэш.HasValue &&
                    !string.IsNullOrWhiteSpace(
                        кэш.Value.Ip) &&
                    кэш.Value.Port > 0)
                {
                    ЗаписатьЛог(
                        $"Сервер взят из кэша: " +
                        $"{кэш.Value.Ip}:" +
                        $"{кэш.Value.Port}");

                    return (
                        кэш.Value.Ip,
                        кэш.Value.Port);
                }
            }
            catch (Exception ошибка)
            {
                ЗаписатьЛог(
                    "Ошибка загрузки кэша сервера: " +
                    ошибка);
            }

            return null;
        }


        // =========================================================
        // ПЕРЕОБНАРУЖЕНИЕ СЕРВЕРА
        // =========================================================

        private async Task ПереобнаружитьАдресAsync(
            CancellationToken токен)
        {
            if (конфигурация == null)
            {
                return;
            }

            var найден =
                await СервисОбнаруженияСервера
                    .НайтиСерверAsync(
                        TimeSpan.FromSeconds(3),
                        токен);

            if (!найден.HasValue)
            {
                return;
            }

            if (string.IsNullOrWhiteSpace(
                    найден.Value.Ip) ||
                найден.Value.Port <= 0)
            {
                return;
            }

            конфигурация.СерверIP =
                найден.Value.Ip;

            конфигурация.СерверПорт =
                найден.Value.Port;

            КэшАдресаСервера.Сохранить(
                найден.Value.Ip,
                найден.Value.Port);

            ЗаписатьЛог(
                $"Адрес сервера переобнаружен: " +
                $"{конфигурация.СерверIP}:" +
                $"{конфигурация.СерверПорт}");
        }


        // =========================================================
        // АВТОЗАПУСК
        // =========================================================

        private void ДобавитьВАвтозапуск()
        {
            try
            {
                var путьПрограммы =
                    Process.GetCurrentProcess()
                        .MainModule?
                        .FileName;

                if (string.IsNullOrWhiteSpace(
                        путьПрограммы))
                {
                    return;
                }

                using var key =
                    Registry.CurrentUser.OpenSubKey(
                        @"Software\Microsoft\Windows\CurrentVersion\Run",
                        writable: true);

                key?.SetValue(
                    "СерьёзныйПатруль",
                    путьПрограммы);
            }
            catch (Exception ошибка)
            {
                ЗаписатьЛог(
                    "Ошибка автозапуска: " +
                    ошибка);
            }
        }


        // =========================================================
        // ОБРАБОТКА ОШИБОК
        // =========================================================

        private static void ОбработатьНеобработанноеИсключение(
            object sender,
            UnhandledExceptionEventArgs e)
        {
            ЗаписатьЛог(
                "FATAL: " +
                e.ExceptionObject);
        }

        private static void ОбработатьНеожиданноеИсключениеЗадачи(
            object? sender,
            UnobservedTaskExceptionEventArgs e)
        {
            ЗаписатьЛог(
                "UNOBSERVED TASK: " +
                e.Exception);

            e.SetObserved();
        }


        private static void ЗаписатьЛог(
            string текст)
        {
            try
            {
                серьёзный.патруль.Сервисы.Лог.Записать(
                    текст);
            }
            catch
            {
            }
        }


        // =========================================================
        // EXIT
        // =========================================================

        protected override void OnExit(
            ExitEventArgs e)
        {
            завершение = true;

            try
            {
                токенИсточника?.Cancel();
            }
            catch
            {
            }

            try
            {
                сервисПатруля?.Остановить();
            }
            catch
            {
            }

            try
            {
                сервисПатруля?.Dispose();
            }
            catch
            {
            }

            сервисПатруля = null;

            try
            {
                токенИсточника?.Dispose();
            }
            catch
            {
            }

            токенИсточника = null;

            base.OnExit(e);
        }
    }
}